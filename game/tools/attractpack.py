#!/usr/bin/env python3
"""attractpack.py VIDDIR OUTDIR: the Arcade attract loop's pictures
(specs/arcade_frontend.md 3.1) as plane-B pictures.

Each picture is a lockstep dump of the arcade's attract (run A, VIDDIR),
composed at the full 384-pixel CPS width and resampled to 320 (the WILLOW
logo and the FBI line fill the arcade's width; a crop would cut them), its
text layer left out where the game types the text natively. CRAM lines 1-3
are fitted to the picture; line 0 stays the screens' text line. A picture
with its text kept (TEXT) is fitted on all four lines.

Writes NAME_tiles.bin, NAME_map.bin (40 x 28 words), NAME_pal.bin (64
words) and attract.h (tile counts)."""
import os, struct, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import intropack  # noqa: E402

# name, dump key, keep the text layer
PICTURES = [
    ("att_cave", 405, False),        # the cave, Bavmorda, Willow with the baby (3.1 t 86-829)
    ("att_willow", 1410, False),     # Willow's framed portrait
    ("att_mad", 2160, False),        # Madmartigan's framed portrait
    ("att_logo", 3330, True),        # the WILLOW logo, the Lucasfilm logo and notice (INSERT COIN off: drawn by the game)
    ("att_capcom", 3555, True),      # the WILLOW logo, the CAPCOM logo and notice
    ("att_fbi", 3750, True),         # the FBI seal and its line
    ("att_dragon", 5550, False),     # the Eborsisk interlude
]
BUDGET = 1100                       # VRAM tiles 226..1325 (screens.c: the fonts before)


def main():
    vid, outdir = sys.argv[1:3]
    out = Path(outdir); out.mkdir(parents=True, exist_ok=True)
    os.environ["CPSFULL"] = "1"
    h = ["/* generated by tools/attractpack.py */"]
    only = set(filter(None, os.environ.get("ONLY", "").split(",")))   # repack only these pictures (attract.h keeps the others' counts)
    if only:
        h = (out / "attract.h").read_text().rstrip("\n").split("\n")
    for name, key, text in PICTURES:
        if only and name not in only:
            continue
        if text: os.environ.pop("CPSPLANE23", None)
        else: os.environ["CPSPLANE23"] = "1"
        import importlib
        importlib.reload(intropack.cpsframe)
        rgb = intropack.cpsframe.compose(intropack.cpsframe.Dump(f"{vid}/v{key:06d}.cps"))
        img = {}
        for y in range(224):
            for x in range(320):
                sx = x * 384 // 320
                img[(x, y)] = intropack.q3(rgb[(y * 384 + sx) * 3:(y * 384 + sx) * 3 + 3])
        lines = [[None] * 16 for _ in range(4)]
        # line 0: INSERT COIN, typed text; the portraits also leave line 1 (their names, yellow)
        free = {l: list(range(1, 16)) for l in ((0, 1, 2, 3) if name == "att_fbi" else (2, 3) if name in ("att_willow", "att_mad") else (1, 2, 3))}
        tiles, words, n = intropack.picture(img, 320, 224, lines, free, BUDGET)
        (out / f"{name}_tiles.bin").write_bytes(tiles)
        (out / f"{name}_map.bin").write_bytes(struct.pack(">1120H", *words))
        (out / f"{name}_pal.bin").write_bytes(struct.pack(">64H", *[intropack.cram_word(c) if c else 0 for l in lines for c in l]))
        d = f"#define {name.upper()}_TILES {len(tiles) // 32}"
        h = [x for x in h if not x.startswith(f"#define {name.upper()}_TILES ")] + [d] if only else h + [d]
        print(f"{name}: {n} tiles")
    (out / "attract.h").write_text("\n".join(h) + "\n")


if __name__ == "__main__":
    main()
