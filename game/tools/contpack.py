#!/usr/bin/env python3
"""contpack.py CONTINUEDUMP.cps OUTDIR: the continue screen's figures
(class 12 kind 3, 0x32710; specs/arcade_frontend.md 7) as one sprite set
for src/screens.c.

Chains (tools/posepack.py "rADDR", each in its own CPS palette group): the
old man lying 0x32AE6, rising on a continue 0x32B02, on GAME OVER 0x32B1E;
the figure by form, Willow 0x32B7A / 0x32B3A (continue), Madmartigan
0x32BD6 / 0x32B8A; the sparks 0xFC96, 0xFD12, 0xFD82, 0xFDE6 (0x32A80); the
burst 0x32414 (class 12 kind 0 variant 5).

The screen's text uses CRAM lines 0-2; the figures get line 3, one
15-colour fit per form (weighted k-means over every pixel of the old man,
the sparks, the burst and that form's figure; tools/sprpal.py's kmeans).

Writes (big-endian): poses.bin (posepack's layout: directory, then
entries, every chain's poses renumbered into one set), tiles0.bin /
tiles1.bin (all tiles, pens for form 0 / 1's line), pal0.bin / pal1.bin (16
CRAM words), anim.bin (chains in the order above, posepack's chain
format with pose numbers into the set) and contfig.h (counts, chain
offsets)."""
import struct, subprocess, sys, tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from sprpal import cram, dist, kmeans, word  # noqa: E402

CHAINS = [("OLD_LIE", "32AE6"), ("OLD_RISE", "32B02"), ("OLD_OVER", "32B1E"),
          ("WIL", "32B7A"), ("WIL_GO", "32B3A"), ("MAD", "32BD6"), ("MAD_GO", "32B8A"),
          ("SPARK0", "FC96"), ("SPARK1", "FD12"), ("SPARK2", "FD82"), ("SPARK3", "FDE6"),
          ("BURST", "32414")]
FORM = {0: {"WIL", "WIL_GO"}, 1: {"MAD", "MAD_GO"}}


def main():
    dump, out = sys.argv[1], Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    sets = []
    with tempfile.TemporaryDirectory() as tmp:
        for name, root in CHAINS:
            d = Path(tmp) / name
            subprocess.run([sys.executable, str(HERE / "posepack.py"), dump, str(d), "r" + root],
                           check=True, capture_output=True, env={"MIRROR": "0", "PREFIX": name, "PATH": "/usr/bin:/bin"})
            poses = (d / "poses.bin").read_bytes()
            count = int((d / "layout.h").read_text().split("_COUNT ")[1].split()[0])
            pal = [cram(struct.unpack_from(">H", (d / "pal.bin").read_bytes(), i * 2)[0]) for i in range(16)]
            sets.append((name, count, poses, (d / "tiles.bin").read_bytes(), pal, (d / "anim.bin").read_bytes()))
    # One pose set: directories first, then all entries; tiles concatenated.
    total = sum(s[1] for s in sets)
    dirs, ents, tiles, anims, owner = bytearray(), bytearray(), bytearray(), bytearray(), []
    chain_at, pose_base = {}, 0
    for name, count, poses, t, pal, anim in sets:
        tbase, ebase = len(tiles) // 32, len(ents) // 6
        nents = (len(poses) - count * 6) // 6
        for i in range(count):
            t0, nt, ns, e0 = struct.unpack_from(">HBBH", poses, i * 6)
            dirs += struct.pack(">HBBH", t0 + tbase, nt, ns, e0 + ebase)
        ents += poses[count * 6:count * 6 + nents * 6]
        tiles += t
        owner += [name] * (len(t) // 32)
        chain_at[name] = len(anims)
        n = anim[0]
        anims += bytes([n]) + b"".join(bytes([anim[1 + 2 * k] + pose_base, anim[2 + 2 * k]]) for k in range(n)) + anim[1 + 2 * n:2 + 2 * n]
        pose_base += count
    pals = {name: pal for name, _, _, _, pal, _ in sets}
    for form in (0, 1):
        hist = {}
        for k in range(len(tiles) // 32):
            name = owner[k]
            if name.startswith(("WIL", "MAD")) and name not in FORM[form]:
                continue
            for b in tiles[k * 32:(k + 1) * 32]:
                for p in (b >> 4, b & 15):
                    if p:
                        c = pals[name][p]
                        hist[c] = hist.get(c, 0) + 1
        line = kmeans(hist, 15) if len(hist) > 15 else sorted(hist) + [(0, 0, 0)] * (15 - len(hist))
        near = {c: 1 + min(range(15), key=lambda j: dist(c, line[j])) for c in hist}
        err = sum(dist(c, line[near[c] - 1]) * w for c, w in hist.items())
        rt = bytearray()
        for k in range(len(tiles) // 32):
            pal = pals[owner[k]]
            for b in tiles[k * 32:(k + 1) * 32]:
                hi, lo = b >> 4, b & 15
                rt.append(((near.get(pal[hi], 1) if hi else 0) << 4) | (near.get(pal[lo], 1) if lo else 0))
        (out / f"tiles{form}.bin").write_bytes(bytes(rt))
        (out / f"pal{form}.bin").write_bytes(struct.pack(">16H", 0, *[word(c) for c in line]))
        print(f"form {form}: {len(hist)} colours -> 15, error {err}")
    (out / "poses.bin").write_bytes(bytes(dirs) + bytes(ents))
    (out / "anim.bin").write_bytes(bytes(anims))
    h = ["/* generated by tools/contpack.py */", f"#define CONTFIG_POSES {total}", f"#define CONTFIG_TILES {len(tiles) // 32}"]
    h += [f"#define CF_{name} {chain_at[name]}" for name, *_ in sets]
    (out / "contfig.h").write_text("\n".join(h) + "\n")
    print(f"contfig: {total} poses, {len(tiles) // 32} tiles, {len(anims)} bytes of chains")


if __name__ == "__main__":
    main()
