#!/usr/bin/env python3
"""gen_spr_data.py DIR OUT.s OUT.h [PREFIX]: assembly .incbin lines and a C header
(extern symbols, pose counts) for every sprite family directory in DIR
(tools/pack_stage1.sh output: poses, tiles, anim, boxes). PREFIX (e.g. s2_)
names another stage's set apart (families shared with stage 1 keep their
poses; only their tiles differ)."""
import hashlib, sys
from pathlib import Path

d, out_s, out_h = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
pre = sys.argv[4] if len(sys.argv) > 4 else ""
fams = sorted(p.name for p in d.iterdir() if (p / "poses.bin").exists())
# Section by stage: stage 1's sets with the common data, stages 2-5 in
# .stagedata (linked last), stage 6's in .s6 (its banks; tools/md_willow.ld).
section = ".rodata" if pre in ("", "s1_") else '.s6,"a"' if pre == "s6_" else '.stagedata,"a"'
s = [f"/* generated by tools/gen_spr_data.py from {d} */", "    .section " + section]
# Stages 2-5: a file identical to one of an earlier stage's sets (stage 1
# first) is not stored again; its symbol is an alias of the earlier one
# (tools/spr_alias_sN.ld, included by tools/md_willow.ld).
earlier = {}
if section == '.stagedata,"a"':
    for k in range(1, int(pre[1])):
        ed, ep = d.parent / f"s{k}spr", "" if k == 1 else f"s{k}_"
        for p in sorted(ed.glob("*/*.bin")):
            if p.stem in ("poses", "anim", "boxes", "sat", "tiles") and (p.parent / "poses.bin").exists():
                earlier.setdefault(hashlib.md5(p.read_bytes()).hexdigest(), f"{ep}{p.parent.name}_{p.stem}")
alias = []
guard = (pre.upper() + "SPR_H") if pre else "S1SPR_H"
h = [f"/* generated by tools/gen_spr_data.py from {d} */", f"#ifndef {guard}", f"#define {guard}"]
for f in fams:
    layout = (d / f / "layout.h").read_text()
    count = int(layout.split("_COUNT ")[1].split()[0])
    s.append(f"    .align 2")
    for part in ("poses", "anim", "boxes", "sat", "tiles"):
        if (d / f / f"{part}.bin").exists():
            same = earlier.get(hashlib.md5((d / f / f"{part}.bin").read_bytes()).hexdigest())
            if same:
                alias.append(f"{pre}{f}_{part} = {same};")
            else:
                s += [f"    .global {pre}{f}_{part}", "    .align 2", f'{pre}{f}_{part}: .incbin "{d}/{f}/{part}.bin"']
            h.append(f"extern const {'s16' if part in ('boxes', 'sat') else 'u8'} {pre}{f}_{part}[];")
    h.append(f"#define {pre.upper()}{f.upper()}_POSES {count}")
    h.append(f"#define {pre.upper()}{f.upper()}_MAX_TILES {int(layout.split('_MAX_TILES ')[1].split()[0])}")
h.append("#endif")
out_s.write_text("\n".join(s) + "\n")
out_h.write_text("\n".join(h) + "\n")
if section == '.stagedata,"a"':
    (Path(__file__).parent / f"spr_alias_{pre[:2]}.ld").write_text(f"/* generated by tools/gen_spr_data.py: {d}'s files identical to an earlier stage's */\n" + "\n".join(alias) + "\n")
print(f"{len(fams)} families" + (f", {len(alias)} files shared with earlier stages" if alias else ""))
