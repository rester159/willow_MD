#!/usr/bin/env python3
"""stagetable.py STAGE OUT.h: a stage's placed objects (ROM 0x4034A ->
entries class, variant, kind, direction, x, y) and its spawn events (ROM
0x9AD8: family, kind, variant, direction, parameter, endX, y, startX,
spawnY) as C tables (specs/stage1_enemies.md 2.1, 2.2)."""
import struct, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
rom = (ROOT / "build/reference_maincpu.bin").read_bytes()
u16 = lambda a: struct.unpack_from(">H", rom, a)[0]
u32 = lambda a: struct.unpack_from(">I", rom, a)[0]
stage, out = int(sys.argv[1]), Path(sys.argv[2])
at = u32(0x4034A + stage * 4)
n = u16(at) + 1
objs = [struct.unpack_from(">BBBBhh", rom, at + 2 + i * 8) for i in range(n)]
# Events: 0x9A92 loads the stage's list; find it the same way (pointer table before 0x9AD8).
ev_at = 0x9AD8
evs = []
import os
yoff = int(os.environ.get("YOFF", "0"))   # native world y = arcade y - YOFF (stage 3: 256, its map starts at y 256)
name = os.environ.get("NAME", "stage_objects")
lines = [f"/* generated by tools/stagetable.py {stage}: ROM 0x{at:X} ({n} objects){' y - %d' % yoff if yoff else ''} */",
         f"static const StageObject {name}[] = {{"]
for c, v, k, d, x, y in objs:
    lines.append(f"    {{ {c}, {v}, {k}, {d}, {x}, {y - yoff if (x or y) else 0} }},")
lines.append("};")
out.write_text("\n".join(lines) + "\n")
print(f"{n} objects")
