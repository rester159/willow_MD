#!/usr/bin/env python3
"""storypack2.py STORYDUMP OUTDIR: stage 2's story page (specs/stage2.md 7.1):
Cherlindrea's picture (scroll2 grid 7, the dump without its text layer) as a
plane-B picture like stage 1's portrait (tools/intropack.py): CRAM lines 0, 2
and 3 fitted to it, line 1 kept for the text (stage 2's sprite line 1).
Writes story2_tiles.bin, story2_map.bin (40 x 28 words), story2_pal.bin
(64 words), story2.h. Her glow's two palette cycles (palettes 4 and 5) are not
reproduced: the picture keeps the dump's colours.
STORY=3 (with SPRPAL=data/s3spr/sprpal.bin): stage 3's page (Fin Raziel,
stage3.md 7.1) as story3_*."""
import os, struct, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import intropack  # noqa: E402

def main():
    dump, outdir = sys.argv[1:3]
    out = Path(outdir); out.mkdir(parents=True, exist_ok=True)
    os.environ["CPSPLANE23"] = "1"
    rgb = intropack.cpsframe.compose(intropack.cpsframe.Dump(dump))
    img = {(x, y): intropack.q3(rgb[(y * 320 + x) * 3:(y * 320 + x) * 3 + 3]) for y in range(224) for x in range(320)}
    root = Path(__file__).resolve().parents[1]
    sprpal = struct.unpack(">32H", (root / os.environ.get("SPRPAL", "data/s2spr/sprpal.bin")).read_bytes())
    k = os.environ.get("STORY", "2")
    cram = lambda w: ((w >> 1) & 7, (w >> 5) & 7, (w >> 9) & 7)
    lines = [[None] * 16, [None] + [cram(w) for w in sprpal[17:32]], [None] * 16, [None] * 16]
    tiles, words, n = intropack.picture(img, 320, 224, lines, {l: list(range(1, 16)) for l in (0, 2, 3)}, intropack.MAP_BUDGET)
    (out / f"story{k}_tiles.bin").write_bytes(tiles)
    (out / f"story{k}_map.bin").write_bytes(struct.pack(">1120H", *words))
    (out / f"story{k}_pal.bin").write_bytes(struct.pack(">64H", *[intropack.cram_word(c) if c else 0 for l in lines for c in l]))
    (out / f"story{k}.h").write_text(f"/* generated by tools/storypack2.py */\n#define STORY{k}_TILES {len(tiles) // 32}\n")
    print(f"story {k} picture: {n} tiles")

if __name__ == "__main__":
    main()
