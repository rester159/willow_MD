#!/usr/bin/env python3
"""torchpack.py DUMP OUTDIR: stage 2's wall torch frames (specs/stage2.md
5.8; class 12 kind 6 variant 0, 0x32FB4): three frames of a 2 x 2 block of
16-px scroll2 cells (table 0x330AC: top-left, bottom-left, top-right,
bottom-right; palette 7), as Genesis tiles on the fort's CRAM line 2
(OUTDIR/pal.bin, from tools/stagepack.py), nearest colours.
Writes torch_tiles.bin (deduplicated, flips shared), torch_words.bin (3
frames x 4 rows x 4 words, row-major: tile index from 0 | line 2 | flips)
and torch.h."""
import struct, sys, zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from cps1_gfx import assemble_region, decode_tile  # noqa: E402
from cps1_palette import cps_rgb  # noqa: E402
from intropack import q3, flip, pack_tile  # noqa: E402

FRAMES = 0x330AC


def main():
    dump, outdir = sys.argv[1:3]
    out = Path(outdir)
    rom = (ROOT / "build/reference_maincpu.bin").read_bytes()
    u16 = lambda a: struct.unpack_from(">H", rom, a)[0]
    with zipfile.ZipFile(ROOT / "willow.zip") as z:
        gfx = assemble_region(z)
    raw = Path(dump).read_bytes()[0x80:]
    pal_ram = raw[0x1C000:0x1C000 + 0x2000]
    colour = lambda p: q3(cps_rgb(int.from_bytes(pal_ram[(0x400 + 7 * 16 + p) * 2:][:2], "big")))
    stage = struct.unpack(">32H", (out / "pal.bin").read_bytes())
    line2 = [((w >> 1) & 7, (w >> 5) & 7, (w >> 9) & 7) for w in stage[0:16]]
    d = lambda a, b: sum((x - y) ** 2 for x, y in zip(a, b))
    pen = lambda c: 1 + min(range(15), key=lambda i: d(c, line2[1 + i]))
    tiles, index, words = [], {}, []
    for f in range(3):
        codes = [u16(FRAMES + f * 8 + k * 2) for k in range(4)]          # TL, BL, TR, BR
        block = {}
        for k, code in enumerate(codes):
            t = decode_tile(gfx, 0x4000 + code, 16)
            bx, by = (k >> 1) * 16, (k & 1) * 16
            for y in range(16):
                for x in range(16):
                    p = t[y][x]
                    block[(bx + x, by + y)] = 0 if p == 15 else pen(colour(p))
        for r in range(4):
            for c in range(4):
                px = tuple(block[(c * 8 + x, r * 8 + y)] for y in range(8) for x in range(8))
                for fl in range(4):
                    key = tuple(flip(list(px), fl))
                    if key in index:
                        words.append(index[key] | (fl << 11) | (2 << 13)); break
                else:
                    index[px] = len(tiles); tiles.append(px); words.append(index[px] | (2 << 13))
    (out / "torch_tiles.bin").write_bytes(b"".join(pack_tile(list(t)) for t in tiles))
    (out / "torch_words.bin").write_bytes(struct.pack(">48H", *words))
    (out / "torch.h").write_text(f"/* generated by tools/torchpack.py */\n#define TORCH_TILES {len(tiles)}\n")
    print(f"torch: {len(tiles)} tiles for 3 frames")


if __name__ == "__main__":
    main()
