#!/usr/bin/env python3
"""Measure four-page palette choices from original CPS RGB and source pixels.

Players retain separate reserved pages. Background tiles retain pages2/3.
NPC16x16 pieces may use any page, with explicit source-pen remaps.
Experiments are offline candidates, never source game behavior or admission.
"""
from pathlib import Path
from collections import Counter,defaultdict
import json,re,struct,zipfile,math,hashlib
from cps1_program import assemble_maincpu
from cps1_gfx import assemble_region,decode_tile
from cps1_palette import palette_words,cps_rgb
from cps1_source_layers import SourceLayers
from native_palette_fit import color_error,fit_palette,nearest_hardware

ROOT=Path(__file__).resolve().parents[1];OUT=ROOT/'build/cartridge-gap-audit'
def cram_rgb(word):return tuple(((word>>s)&7)*34 for s in (1,5,9))
def cram_word(rgb):return sum((v//34)<<s for v,s in zip(rgb,(1,5,9)))
def metrics(items,palettes,assign=None):
 errors=Counter();n=0;source=set();used=set();delta=[0,0,0];weighted=0
 look={c:[min((color_error(c,p),j) for j,p in enumerate(pal)) for pal in palettes] for c in {c for item in items for c in item['hist']}}
 for i,item in enumerate(items):
  page=assign[i] if assign is not None else min(item['allowed'],key=lambda page:sum(k*look[c][page][0] for c,k in item['hist'].items()))
  for c,k in item['hist'].items():
   q=palettes[page][look[c][page][1]];source.add(c);used.add(q);n+=k
   errors['rgb']+=k*sum((a-b)**2 for a,b in zip(c,q));weighted+=k*color_error(c,q)
   for channel in range(3):delta[channel]+=k*(q[channel]-c[channel])
 return {'pixels':n,'source_colors':len(source),'output_colors':len(used),'rgb_rmse':math.sqrt(errors['rgb']/max(1,3*n)),'chroma_weighted_mean_error':weighted/max(1,n),'mean_rgb_shift':[v/max(1,n) for v in delta]}
def assignments(items,palettes):
 colors={c for item in items for c in item['hist']}
 look={c:[min(color_error(c,p) for p in page) for page in palettes] for c in colors}
 return [min(item['allowed'],key=lambda s:(sum(n*look[c][s] for c,n in item['hist'].items()),s)) for item in items]
def fit_joint(bg,objects,players,initial,weight):
 items=bg+objects;palettes=[list(p) for p in initial];best=None
 for iteration in range(8):
  assign=assignments(items,palettes)
  hist=[Counter(),Counter()]
  for i,(item,page) in enumerate(zip(items,assign)):
   if page<2:continue
   for color,n in item['hist'].items():hist[page-2][color]+=n*(weight if i>=len(bg) else 1)
  next_palettes=[players[0],players[1],fit_palette(hist[0]),fit_palette(hist[1])]
  bgm=metrics(bg,palettes);objm=metrics(objects,palettes)
  objective=bgm['chroma_weighted_mean_error']*bgm['pixels']+weight*objm['chroma_weighted_mean_error']*objm['pixels']
  if best is None or objective<best[0]:best=(objective,[list(p) for p in palettes],iteration)
  if next_palettes==palettes:break
  palettes=next_palettes
 return best[1],best[2]
def main():
 program=assemble_maincpu(ROOT/'willow.zip')
 with zipfile.ZipFile(ROOT/'willow.zip') as z:gfx=assemble_region(z)
 layers=SourceLayers(program,gfx)
 source_words={g:[w|0xf000 for w in palette_words(program,'base',0,g)] for g in (0,1,10,31)}
 players=[[nearest_hardware(cps_rgb(w)) for w in source_words[g][:15]] for g in (0,1)]
 text=(ROOT/'native/intro_probe/src/layers.h').read_text().split('intro_palettes[2][16]=')[1].split(';')[0]
 words=[int(v,0) for v in re.findall(r'0x[0-9a-fA-F]+|\b\d+\b',text)]
 assert len(words)==32
 bgpal=[[cram_rgb(w) for w in words[start+1:start+16]] for start in (0,16)]
 initial=players+bgpal
 bg=[];forest=[];bgwordsets=defaultdict(set)
 for layer,origin,height in ((2,-752,736),(3,-496,480)):
  pal=[[w|0xf000 for w in palette_words(program,f'scroll{layer}',0,g)] for g in range(32)]
  for ty in range(height//8):
   for tx in range(40):
    h=Counter()
    for py in range(8):
     for px in range(8):
      pen,group=layers.pen(layer,32+tx*8+px,origin+ty*8+py)
      if pen!=15:h[cps_rgb(pal[group][pen])]+=1;bgwordsets[layer].add(pal[group][pen])
    item={'hist':h,'allowed':(2,3),'layer':layer,'x':32+tx*8,'y':origin+ty*8}
    bg.append(item)
    if item['y']>=-240:forest.append(item)
 print('Loaded background source cells',len(bg),flush=True)
 catalog=json.loads((OUT/'opening_object_tiles.json').read_text())
 pairs=set()
 for frame in catalog['captures']:
  raw=Path(frame['path']).read_bytes();bank=struct.unpack('>1024H',raw[frame['bank']:frame['bank']+0x800])
  # Include complete graphic blocks for every on-crop piece, as generated by
  # the catalog; retain source palette identity separately from deduplication.
  for at in range(0,1024,4):
   x,y,base,a=bank[at:at+4]
   if a&0xff00==0xff00:break
   if base>0x27ff:continue
   nx=((a>>8)&15)+1;ny=(a>>12)+1
   for row in range(ny):
    for col in range(nx):
     sx=(x+col*16)&511;sy=(y+row*16)&511
     px=(496-sx if frame['global_flip'] else sx)-96;py=(240-sy if frame['global_flip'] else sy)-16
     if px>=320 or px+16<=0 or py>=224 or py+16<=0:continue
     cx=nx-1-col if a&32 else col;cy=ny-1-row if a&64 else row
     code=(base&~15)+((base+cx)&15)+cy*16;group=a&31
     captured=list(struct.unpack('>16H',raw[0x1c000+group*32:0x1c020+group*32]))
     assert captured==source_words[group],(frame['path'],group)
     pairs.add((code,group))
 objects=[]
 for code,group in sorted(pairs):
  pens=decode_tile(gfx,code,16);colors=[cps_rgb(w) for w in source_words[group]]
  h=Counter(colors[p] for row in pens for p in row if p!=15)
  objects.append({'code':code,'group':group,'hist':h,'allowed':(group,) if group<2 else (0,1,2,3)})
 npc=[o for o in objects if o['group']>=2]
 report={'source_palette_words':source_words,'background_source_words':{k:sorted(v) for k,v in bgwordsets.items()},'current_background_cram':words,'reserved_player_cram':[[0]+[cram_word(p) for p in page] for page in players],'scope':'All source intro layer cells, plus unique captured source-code/palette object pieces. Full RGB888 until palette fitting; no invented tint, no opaque pen mapped to transparent. Players reserve separate nearest-hardware pages; this is not full-stage or mutable-palette admission.','candidates':[]}
 allcolors={cps_rgb(w) for g in source_words for w in source_words[g][:15]}
 # Opaque black is a real visible color; exclude only each reserved pen zero.
 bgcolors={cram_rgb(w) for w in words[1:16]+words[17:32]}
 quantized={nearest_hardware(c) for c in allcolors}
 report['color_union']={'object_rgb_colors':len(allcolors),'object_nearest_hardware_colors':len(quantized),'current_background_hardware_colors':len(bgcolors),'combined_nearest_hardware_colors':len(quantized|bgcolors),'players_nearest_hardware_colors':len(set(players[0]+players[1])),'object_background_exact_hardware_reuse':len(quantized&bgcolors),'object_hardware_rgb':sorted(quantized),'background_hardware_rgb':sorted(bgcolors),'per_group_hardware_rgb':{g:sorted({nearest_hardware(cps_rgb(w)) for w in source_words[g][:15]}) for g in source_words}}
 oldactor=[cram_rgb(w) for w in json.loads((ROOT/'build/intro-sprite-assets.json').read_text())['palette'][1:]]
 report['previous_intro_npc_fit']=metrics([dict(o,allowed=(0,)) for o in npc],[oldactor])
 variants=[('unchanged_background',initial,None)]
 for weight in (0,1,4,16):
  print('Fitting NPC weight',weight,flush=True)
  pal,iteration=fit_joint(bg,npc,players,initial,weight);variants.append((f'joint_weight_{weight}',pal,iteration))
 for name,pal,iteration in variants:
  row={'name':name,'iteration':iteration,'cram':[[0]+[cram_word(c) for c in page] for page in pal],'background':metrics(bg,pal),'forest':metrics(forest,pal),'objects':metrics(objects,pal),'npc':metrics(npc,pal),'per_group':{str(g):metrics([o for o in objects if o['group']==g],pal) for g in (0,10,31)}}
  report['candidates'].append(row);print(name,row['background']['rgb_rmse'],row['npc']['rgb_rmse'],flush=True)
 report['background_tile_count']=len(bg);report['unique_object_code_groups']=len(objects)
 report['no_claim_of_global_optimum']='Deterministic alternating fit candidates, not an exhaustive four-palette optimum. Keep source-player pages fixed; compare Pareto tradeoffs separately.'
 (OUT/'object-palette-fit.json').write_text(json.dumps(report,indent=2)+'\n')
 # Export explicit candidate maps and remapped pattern variants. No palette
 # page writes occur here; runtime activation must check matching source words.
 raw_catalog=dict(catalog['entries']);raw=(OUT/'opening_object_tiles.bin').read_bytes()
 for name,pal,_ in variants:
  maps=[];map_ids={};entries=[];blocks=[bytes(128)];ids={blocks[0]:0}
  assign=assignments(objects,pal)
  for obj,page in zip(objects,assign):
   code,group=obj['code'],obj['group'];colors=[cps_rgb(w) for w in source_words[group]]
   mapping=[0]+[1+min(range(15),key=lambda i:(color_error(colors[p],pal[page][i]),i)) for p in range(15)]
   assert mapping[0]==0 and all(1<=p<=15 for p in mapping[1:])
   key=(group,page,tuple(mapping))
   if key not in map_ids:map_ids[key]=len(maps);maps.append({'source_group':group,'source_words':source_words[group],'page':page,'pens':mapping})
   source=raw[raw_catalog[code]*128:(raw_catalog[code]+1)*128]
   remapped=bytes((mapping[v>>4]<<4)|mapping[v&15] for v in source)
   if remapped not in ids:ids[remapped]=len(blocks);blocks.append(remapped)
   entries.append({'code':code,'source_group':group,'source_block':raw_catalog[code],'variant_block':ids[remapped],'map':map_ids[key]})
  plan={'name':name,'source_palettes':source_words,'source_binary_sha256':catalog['binary_sha256'],'cram':[[0]+[cram_word(c) for c in page] for page in pal],'maps':maps,'entries':entries,'blocks':len(blocks),'binary_sha256':hashlib.sha256(b''.join(blocks)).hexdigest(),'scope':'Explicit fitted variant catalog for saved opening source-code/group coverage; invalid unless every source palette word and CRAM plan matches, including both reserved player groups.'}
  (OUT/f'object_palette_{name}.bin').write_bytes(b''.join(blocks));(OUT/f'object_palette_{name}.json').write_text(json.dumps(plan,indent=2)+'\n')
 print('Wrote explicit pen-remap candidates',flush=True)
if __name__=='__main__':main()
