#!/usr/bin/env python3
"""Compose an opt-in continuous native sprite preparation/publication gate.

No host positions or expected SAT data enter the target. Both bus variants run
identical native work. Source timing is observed, never patched to make it pass.
"""
import argparse, contextlib, hashlib, io, json, re, subprocess, tempfile
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
BASE=ROOT/'build/native-object-publication/checkpoint-compact-v1'
RESOURCES=ROOT/'build/native-route-objects/prepared-v2'
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def array(name,data,size):
    assert len(data)%size==0
    values=[int.from_bytes(data[n:n+size],'big')for n in range(0,len(data),size)]
    return 'static const uint%d_t %s[]={\n'%(size*8,name)+''.join(','.join('0x%x%s'%(v,'UL'if size==4 else'')for v in values[n:n+12])+',\n'for n in range(0,len(values),12))+'};\n'
def build(out,palette,retained=False,reuse_only=False,content_stream=False,background=None,hardware_irq_mask=False,background_live=None,background_lookup=None,background_near_columns=None,background_columns=False,background_far_stream=None,background_shared_stream=None):
    assert background_shared_stream is None or background_far_stream is not None
    assert background_far_stream is None or (background_columns and background_live is not None and background is not None and content_stream),'Far streaming requires the live columns/resident/content renderer'
    if background_far_stream is not None:
        assert all(out.resolve()!=path.resolve() for path in [background_far_stream,background_live,background]),'Output aliases a far-stream resource input directory'
    out.mkdir(parents=True,exist_ok=True)
    pinned=json.loads((BASE/'checkpoint.json').read_text())['files']
    for n in ['program.bin','program-original.bin','platform.bin','platform-original.bin','platform-addresses.h']:
        assert sha(BASE/n)==pinned[n]
    resource_manifest=json.loads((RESOURCES/'manifest.json').read_text())
    # Header/ROM bytes are generated by the checked native route resource tool.
    dependency_names=['route_objects.h','object-patterns.bin','source-palettes.bin','cram.bin']
    inputs={str(RESOURCES/n):sha(RESOURCES/n)for n in dependency_names}
    for n in dependency_names:assert sha(RESOURCES/n)==resource_manifest['outputs'][n]
    extra_rom=None
    far_layout=None;far_manifest=None;far_aux=None;far_code=None
    background_bytes=0
    assert background_live is None or (background is not None and content_stream)
    assert background_lookup is None or background_live is not None
    assert background_near_columns is None or background_live is not None
    assert not background_columns or background_live is not None
    hardware_irq_mask=hardware_irq_mask or background is not None
    if background is not None:
        background=background.resolve()
        background_manifest=json.loads((background/'manifest.json').read_text())
        blob=background/'resident-upload.bin'
        assert sha(blob)==background_manifest['outputs']['resident-upload.bin']
        data=blob.read_bytes()
        assert data[:8]==bytes.fromhex('5742523100010002')
        assert int.from_bytes(data[8:12],'big')==len(data)
        assert int.from_bytes(data[12:16],'big')==16
        assert 0x110000+len(data)<=0x200000
        background_bytes=len(data)
        if background_live is not None:
            catalog=background_live.resolve();cm=json.loads((catalog/'manifest.json').read_text())
            for n in ['catalog.bin','catalog_imports.h']:
                assert sha(catalog/n)==cm['outputs'][n]
                inputs[str(catalog/n)]=sha(catalog/n)
            inputs[str(catalog/'manifest.json')]=sha(catalog/'manifest.json')
            (out/'render_background_imports.h').write_bytes((catalog/'catalog_imports.h').read_bytes())
            assert len(data)<=0x10000
            data+=bytes(0x10000-len(data))+(catalog/'catalog.bin').read_bytes()
            if background_lookup is not None:
                lookup=background_lookup.resolve();lm=json.loads((lookup/'manifest.json').read_text())
                assert lm['origin']==0x140000 and lm['catalog_origin']==0x120000
                assert lm['inputs'][str(catalog/'catalog.bin')]==sha(catalog/'catalog.bin')
                for n in ['lookup.bin','lookup_imports.h']:
                    assert sha(lookup/n)==lm['outputs'][n]
                    inputs[str(lookup/n)]=sha(lookup/n)
                inputs[str(lookup/'manifest.json')]=sha(lookup/'manifest.json')
                (out/'render_background_lookup_imports.h').write_bytes((lookup/'lookup_imports.h').read_bytes())
                assert len(data)<=0x30000 and (lookup/'lookup.bin').stat().st_size==lm['bytes']
                data+=bytes(0x30000-len(data))+(lookup/'lookup.bin').read_bytes()
            if background_near_columns is not None:
                columns=background_near_columns.resolve();nm=json.loads((columns/'manifest.json').read_text())
                assert nm['address']==0x142000 and nm['pair_stride']==16 and nm['column_stride']==8
                assert nm['bytes']==nm['count']*16
                assert nm['inputs'][str(catalog/'catalog.bin')]==sha(catalog/'catalog.bin')
                assert nm['inputs'][str(catalog/'catalog_imports.h')]==sha(catalog/'catalog_imports.h')
                for n in ['near-columns.bin','near_columns_imports.h']:
                    assert sha(columns/n)==nm['outputs'][n]
                    inputs[str(columns/n)]=sha(columns/n)
                inputs[str(columns/'manifest.json')]=sha(columns/'manifest.json')
                (out/'render_background_near_columns_imports.h').write_bytes((columns/'near_columns_imports.h').read_bytes())
                assert len(data)<=0x32000 and (columns/'near-columns.bin').stat().st_size==nm['bytes']
                data+=bytes(0x32000-len(data))+(columns/'near-columns.bin').read_bytes()
        assert 0x110000+len(data)<=0x200000
        if background_far_stream is not None:
            from verify_native_background_far_stream import verify
            far=background_far_stream.resolve();far_manifest=json.loads((far/'manifest.json').read_text())
            far_layout=json.loads((far/'layout.json').read_text())
            origin=far_manifest['origin'];far_data=(far/'far-stream.bin').read_bytes()
            assert origin%4==0 and 0x150000<=origin and origin+len(far_data)<=0x200000,'WBF1 overlaps auxiliary code or source SRAM'
            assert len(far_data)==far_manifest['bytes']==far_layout['total_bytes']
            assert json.loads((catalog/'layout.json').read_text())['origin']==0x120000,'Catalog is not at its packed ROM address'
            assert 0x110000+len(data)<=0x146000,'Existing immutable resources overlap auxiliary code'
            # The independent parser checks every WBF1 field/import/attribute,
            # full source identities and all six SHA bindings against exactly
            # this catalog/residency. Keep its proof without random temp paths.
            with tempfile.TemporaryDirectory(prefix='far-validation-',dir=out) as tmp:
                proof=Path(tmp)/'proof'
                with contextlib.redirect_stdout(io.StringIO()):
                    verify(far,catalog,background,ROOT/'build/native-route-background-audit/checkpoint-v1',proof)
                (out/'far-stream-validation.json').write_bytes((proof/'evidence.json').read_bytes())
            for name,digest in far_manifest['inputs'].items():
                assert sha(Path(name))==digest,('Far resource input changed',name)
                inputs[name]=digest
            for name,digest in far_manifest['outputs'].items():
                assert sha(far/name)==digest,('Far resource output changed',name)
                inputs[str(far/name)]=digest
            inputs[str(far/'manifest.json')]=sha(far/'manifest.json')
            (out/'render_background_far_stream_imports.h').write_bytes((far/'far_stream_imports.h').read_bytes())
            data+=bytes(origin-0x110000-len(data))+far_data
        if background_shared_stream is not None:
            from verify_native_background_shared_stream import verify as verify_shared
            shared=background_shared_stream.resolve()
            shared_manifest=json.loads((shared/'manifest.json').read_text())
            shared_proof=verify_shared(shared)
            # Bind to the exact resources packed by this build, not merely an
            # independently valid catalog or physical image elsewhere.
            for bound in [far/'far-stream.bin',catalog/'catalog.bin',background/'entries.json']:
                assert shared_manifest['inputs'][str(bound.resolve())]==sha(bound)
            shared_origin=shared_manifest['origin'];shared_data=(shared/'shared-stream.bin').read_bytes()
            assert shared_origin>=0x110000+len(data) and shared_origin+len(shared_data)<=0x200000
            data+=bytes(shared_origin-0x110000-len(data))+shared_data
            for name,digest in shared_manifest['inputs'].items():inputs[name]=digest
            for name,digest in shared_manifest['outputs'].items():inputs[str(shared/name)]=digest
            inputs[str(shared/'manifest.json')]=sha(shared/'manifest.json')
            (out/'shared-stream-validation.json').write_text(json.dumps(shared_proof,indent=2)+'\n')
            (out/'render_background_shared_stream_imports.h').write_bytes((shared/'shared_stream_imports.h').read_bytes())
        (out/'background-resources.bin').write_bytes(data)
        inputs.update({str(p):sha(p)for p in [background/'manifest.json',blob]})
        extra_rom={'file':'background-resources.bin','origin':0x110000,'bytes':len(data),'sha256':sha(out/'background-resources.bin')}
    assert len((RESOURCES/'object-patterns.bin').read_bytes())==16000
    assert len((RESOURCES/'source-palettes.bin').read_bytes())==6144
    (out/'render_resources.h').write_text(array('renderPatterns',(RESOURCES/'object-patterns.bin').read_bytes(),4)+array('renderSourcePalettes',(RESOURCES/'source-palettes.bin').read_bytes(),4)+array('renderColors',(RESOURCES/'cram.bin').read_bytes(),2))
    imports=(BASE/'platform-addresses.h').read_text()
    (out/'render_imports.h').write_text(re.sub(r'(0x[0-9a-f]+)u',r'\1',imports))
    far_fields=['owner','displayedUse','preparedUse','slots','key','requested','completed','phase','residencyEpoch','sourceEpoch','paletteEpoch','preparationGeneration','view','cursor','preparedResidencyEpoch','missing','reserved']
    if background_far_stream is not None:
        (out/'render_far_layout.c').write_text('#include <stdint.h>\n#include <stddef.h>\n#include "willow_native_far_cache.h"\nconst uint32_t renderFarCacheLayout[] __attribute__((used,section(".willow_far_stream.abi")))={sizeof(WillowNativeFarCache),'+','.join('offsetof(WillowNativeFarCache,%s)'%field for field in far_fields)+'};\n')
    symbols=None;products={};patches=[];symbol_sizes=None;compile_commands=[];far_boot_patch=None
    for original in (True,False):
        suffix='-original'if original else'';name='render'+suffix
        elf=out/(name+'.elf')
        command=['m68k-elf-gcc','-m68000','-O2','-ffreestanding','-fno-builtin','-fstack-usage','-nostdlib','-Wall','-Wextra','-Werror',
                 '-I'+str(ROOT/'src'),'-I'+str(RESOURCES),'-I'+str(out),
                 *(['-DRENDER_ORIGINAL_BUS=1']if original else[]),
                 *(['-DRENDER_RETAINED=1']if retained else[]),
                 *(['-DRENDER_DIRTY_UPLOAD=1']if retained and not reuse_only and not content_stream else[]),
                 *(['-DRENDER_CONTENT_STREAM=1']if content_stream else[]),
                 *(['-DRENDER_BACKGROUND_RESIDENT=1','-DRENDER_BACKGROUND_BYTES='+str(background_bytes)]if extra_rom else[]),
                 *(['-DRENDER_BACKGROUND_LIVE=1','-DWILLOW_BG_SCROLL2_BASE='+str(0x918000 if original else 0x204000),'-DWILLOW_BG_SCROLL3_BASE='+str(0x914000 if original else 0x208000),'-Wl,--defsym=__render_bss_limit=0xff7000']if background_live else[]),
                 *(['-DRENDER_BACKGROUND_LOOKUP=1']if background_lookup else[]),
                 *(['-DRENDER_BACKGROUND_NEAR_STRIP=1','-DWILLOW_NATIVE_NEAR_STRIP_PREPARED=1']if background_near_columns else[]),
                 *(['-DRENDER_BACKGROUND_COLUMNS=1']if background_columns else[]),
                 *(['-DRENDER_BACKGROUND_FAR_STREAM=1','-DWILLOW_NATIVE_FAR_AUX_CODE=1']if background_far_stream else[]),
                 *(['-DRENDER_BACKGROUND_SHARED_STREAM=1']if background_shared_stream else[]),
                 '-Wl,-T,tools/native_render_cadence.ld','tools/native_render_cadence.c','tools/native_render_cadence.S',
                 *([str(out/'render_far_layout.c')]if background_far_stream else[]),
                 *(['tools/native_background_columns_hooks.S','tools/native_background_columns_abi.c']if background_columns else ['tools/native_background_writer_hooks.S','tools/native_background_writer_abi.c']if background_live else[]),'-o',str(elf)]
        compile_commands.append(command)
        subprocess.run(command,cwd=ROOT,check=True)
        binary=out/(name+'.bin');subprocess.run(['m68k-elf-objcopy','-O','binary','-R','.willow_far_stream',str(elf),str(binary)],check=True)
        sym=subprocess.check_output(['m68k-elf-nm','-n',str(elf)],text=True);(out/(name+'.sym')).write_text(sym)
        (out/(name+'.disasm')).write_text(subprocess.check_output(['m68k-elf-objdump','-d',str(elf)],text=True))
        current={r.split()[2]:int(r.split()[0],16)for r in sym.splitlines()if len(r.split())==3}
        if background_far_stream:
            sized=subprocess.check_output(['m68k-elf-nm','-S','-n',str(elf)],text=True)
            (out/(name+'-sized.sym')).write_text(sized)
            sizes={row.split()[3]:(int(row.split()[0],16),int(row.split()[1],16))for row in sized.splitlines()if len(row.split())==4}
            if symbol_sizes is None:symbol_sizes=sizes
            else:assert symbol_sizes==sizes,'Both buses must have identical auxiliary/ABI symbol extents'
        if symbols is None:symbols=current
        else:assert symbols==current,'Original and relocated helpers must have identical code layout'
        aux_begin=current['__render_far_code_begin'];aux_end=current['__render_far_code_end']
        assert aux_begin==0x146000 and aux_begin<=aux_end<=0x150000
        if background_far_stream is not None:
            auxiliary=out/(name+'-far-stream.bin')
            subprocess.run(['m68k-elf-objcopy','-O','binary','-j','.willow_far_stream',str(elf),str(auxiliary)],check=True)
            aux_data=auxiliary.read_bytes();assert len(aux_data)==aux_end-aux_begin
            if far_code is None:far_code=aux_data
            else:assert far_code==aux_data,'Common auxiliary ROM must be byte-identical on both source buses'
            if original:far_aux={'origin':aux_begin,'end_exclusive':aux_end,'bytes':len(aux_data),'file':'render-far-stream.bin','sha256':sha(auxiliary)}
        else:assert aux_end==aux_begin,'Auxiliary code requires explicit --background-far-stream'
        program=bytearray((BASE/('program'+suffix+'.bin')).read_bytes())
        platform=bytearray((BASE/('platform'+suffix+'.bin')).read_bytes())
        if background_far_stream is not None:
            # Source6F2 clears all WRAM after native VDP boot. Select a checked
            # native continuation without modifying the original clear body.
            clear=bytes.fromhex('41f900ff0000383c1fff700020c020c051ccfffa4ed4')
            assert program[0x6f2:0x6f2+len(clear)]==clear,'Original WRAM clear changed'
            old=bytes.fromhex('287c000005b64ef806f2')
            at=0x10005e-0x100010
            assert platform.count(old)==1 and platform[at:at+len(old)]==old,'Platform source-clear continuation changed'
            target=symbols['renderFarAfterSourceClear']
            assert aux_begin<=target<aux_end
            replacement=old[:2]+target.to_bytes(4,'big')+old[6:]
            platform[at:at+len(old)]=replacement
            if original:far_boot_patch={'address':0x10005e,'expected':old.hex(),'replacement':replacement.hex(),'source_clear_address':0x6f2,'source_clear_bytes':clear.hex(),'continuation':0x5b6}
        for at,old,target in [(0x3b564,0x101066,'renderSingle'),(0x3b56c,0x10105c,'renderDouble')]:
            expected=bytes.fromhex('4eb9')+old.to_bytes(4,'big');replacement=bytes.fromhex('4eb9')+symbols[target].to_bytes(4,'big')
            assert program[at:at+6]==expected
            program[at:at+6]=replacement
            if original:patches.append({'at':at,'expected':expected.hex(),'replacement':replacement.hex()})
        at=0x10006e-0x100010;assert platform[at:at+6]==bytes.fromhex('4eb900101112')
        platform[at:at+6]=bytes.fromhex('4eb9')+symbols['renderAcquireAndPublish'].to_bytes(4,'big')
        assert program[0x1554:0x1558]==bytes.fromhex('48e7fffe')
        if background_live:
            if background_columns:
                from build_native_background_columns import LEAVES,BULKS,LEAF_PATCH_OPCODE,LOOP_TAILS
            else:
                from build_native_background_writer import LEAVES,BULKS,LEAF_PATCH_OPCODE,LOOP_TAILS
            assert LEAF_PATCH_OPCODE==0x4ef9
            for (at,name,body),tail in zip(LEAVES,LOOP_TAILS):
                full=bytes.fromhex(body+tail)
                assert program[at:at+len(full)]==full,('Source leaf loop changed',hex(at))
            spans=[(at,name,bytes.fromhex(old))for at,name,old in LEAVES]
            spans += [(at,name,(bytes.fromhex(body+tail))[:6])for at,name,body,tail in BULKS]
            controller='willowBackgroundColumnsController' if background_columns else 'willowBackgroundController'
            spans += [(0x3b52a,controller+'2',bytes.fromhex('4eb900042602')),(0x3b530,controller+'3',bytes.fromhex('4eb900042f48')),(0x15b4,'renderBackgroundEndIRQ',bytes.fromhex('4cdf7fff4e73'))]
            for at,name,expected in spans:
                assert program[at:at+len(expected)]==expected,(hex(at),program[at:at+len(expected)].hex())
                replacement=bytes.fromhex('4ef9' if at==0x15b4 or at in [p[0]for p in BULKS+LEAVES] else '4eb9')+symbols[name].to_bytes(4,'big')+bytes.fromhex('4e71')*((len(expected)-6)//2)
                program[at:at+len(expected)]=replacement
                if original:patches.append({'at':at,'expected':expected.hex(),'replacement':replacement.hex()})
        old=bytes.fromhex('4ef815540000');assert platform.count(old)==1
        at=platform.index(old);platform[at:at+6]=bytes.fromhex('4ef9')+symbols['renderSourceIRQ'].to_bytes(4,'big')
        if hardware_irq_mask:
            # The restored native IRQ SR already has I=6. CPS VINT level2
            # blocks another level2; Genesis VINT level6 must likewise remain
            # blocked until original RTE. Lowering to2 allowed real level6
            # nesting, including between the former ANDI/ORI instructions.
            old=bytes.fromhex('46df027cf8ff007c2200');assert platform.count(old)==1
            at=platform.index(old)+2
            platform[at:at+8]=bytes.fromhex('4e714e714e714e71')
        old=bytes.fromhex('33fc812400c00004');assert platform.count(old)==1
        at=platform.index(old);platform[at:at+8]=bytes.fromhex('4eb9')+symbols['nativeRenderVDPBoot'].to_bytes(4,'big')+bytes.fromhex('4e71')
        start=0x102000-0x100010;assert len(platform)<start
        platform.extend(bytes(start-len(platform)));platform.extend(binary.read_bytes())
        if palette is not None:
            manifest=json.loads((palette/'manifest.json').read_text())
            assert sha(palette/'manifest.json')=='261b6d8e17122cca06fe447fcd3be40fe3b154bd84af1fb481bf5811f4c6584b'
            assert sha(palette/'evidence.json')=='9444ff7314fe6d82f4e378010b8f6b0dc47809c2d50ecca35db948ed4debb896'
            blob=(palette/'hooks.bin').read_bytes()
            assert sha(palette/'hooks.bin')==manifest['blob_sha256']
            for patch in manifest['source_patches']:
                at=patch['address'];expected=bytes.fromhex(patch['expected']);replacement=bytes.fromhex(patch['replacement'])
                assert program[at:at+len(expected)]==expected
                program[at:at+len(expected)]=replacement
            offset=manifest['rom_start']-0x100010
            assert len(platform)<=offset
            platform.extend(bytes(offset-len(platform)));platform.extend(blob)
            assert len(platform)<=65520
        for n,data in [('program'+suffix+'.bin',program),('platform'+suffix+'.bin',platform)]:
            (out/n).write_bytes(data);products[n]=sha(out/n)
    if background_far_stream is not None:
        # Keep the platform's established bounded64KiB image. Place only the
        # separately extracted code in the predeclared common extra-ROM gap.
        resource_image=bytearray((out/extra_rom['file']).read_bytes())
        offset=far_aux['origin']-extra_rom['origin']
        assert offset>=0 and offset+len(far_code)<=len(resource_image)
        assert not any(resource_image[offset:offset+len(far_code)])
        resource_image[offset:offset+len(far_code)]=far_code
        (out/extra_rom['file']).write_bytes(resource_image)
        extra_rom['sha256']=sha(out/extra_rom['file'])
    header=imports+'#define RENDER_ATOMIC_PHASE_STATUS 1\n'
    header+='#define RENDER_IRQ_SOURCE_BRIDGE 0x%xu\n'%symbols['renderSourceIRQ']
    header+='#define RENDER_SOURCE_CONTEXT_READY 0x%xu\n#define RENDER_SOURCE_CONTEXT_SP 0x%xu\n'%(symbols['renderSourceContextReady'],symbols['renderPrepareSP'])
    if retained and not reuse_only and not content_stream:
        header+='#define RENDER_RETAINED_SAT 1\n'
        header+='#define RENDER_RETAINED_BASE 0x%xu\n#define RENDER_RETAINED_PLAN 0x%xu\n'%(symbols['renderRetained'],symbols['plan'])
        blob=(out/'render.bin').read_bytes();at=symbols['renderRetainedLayout']-0x102000
        names=['BYTES','WORDS_OFFSET','GENERATION_OFFSET','COMMAND_OFFSET','PLAN_OFFSET','EPOCH_OFFSET','COUNT_OFFSET','CAPACITY_OFFSET','READY_OFFSET']
        for n,name in enumerate(names):header+='#define RENDER_RETAINED_%s %du\n'%(name,int.from_bytes(blob[at+n*4:at+n*4+4],'big'))
    if content_stream:
        header+='#define RENDER_CONTENT_STREAM 1\n'
        for macro,symbol in [('RENDER_CONTENT_ID_ADDRESS','renderPublishedGeometryId'),('RENDER_CONTENT_PALETTE_ADDRESS','renderPublishedPalette'),('RENDER_CONTENT_COUNT_ADDRESS','renderPublishedCount')]:header+='#define %s 0x%xu\n'%(macro,symbols[symbol])
    if extra_rom:
        header+='#define RENDER_BACKGROUND_RESIDENT 1\n#define RENDER_BACKGROUND_BYTES %du\n'%background_bytes
    if background_live:
        header+='#define RENDER_BACKGROUND_LIVE 1\n'
        for macro,symbol in [('RENDER_BG_CODE_BEGIN','__render_code_begin'),('RENDER_BG_CODE_END','__render_code_end'),('RENDER_BG_RTE_PC','renderBackgroundRTE'),('RENDER_BG_IRQ_SP','renderBackgroundIRQSP')]:header+='#define %s 0x%xu\n'%(macro,symbols[symbol])
    if background_columns:header+='#define RENDER_BACKGROUND_COLUMNS 1\n#define RENDER_BACKGROUND_COLUMNS_STATE 0x%xu\n'%symbols['willowNativeBackgroundColumnsState']
    if background_far_stream:
        header+='#define RENDER_BACKGROUND_FAR_STREAM 1\n#define RENDER_BG_FAR_CODE_BEGIN 0x%xu\n#define RENDER_BG_FAR_CODE_END 0x%xu\n'%(far_aux['origin'],far_aux['end_exclusive'])
        header+='#define RENDER_BG_FAR_RESOURCE_BEGIN 0x%xu\n#define RENDER_BG_FAR_RESOURCE_END 0x%xu\n'%(far_manifest['origin'],far_manifest['origin']+far_manifest['bytes'])
        at=symbols['renderFarCacheLayout']-far_aux['origin']
        assert at>=0 and at+4*(len(far_fields)+1)<=len(far_code)
        layout_values=[int.from_bytes(far_code[at+n*4:at+n*4+4],'big')for n in range(len(far_fields)+1)]
        assert layout_values[0]==436,'Native far-cache ABI changed'
        header+='#define RENDER_BG_FAR_CACHE_BYTES %du\n'%layout_values[0]
        for field,value in zip(far_fields,layout_values[1:]):
            macro=re.sub(r'(?<!^)(?=[A-Z])','_',field).upper()
            header+='#define RENDER_BG_FAR_CACHE_%s_OFFSET %du\n'%(macro,value)
            header+='#define RENDER_FAR_CACHE_%s_OFFSET %du\n'%(field.upper(),value)
        header+='#define RENDER_FAR_CACHE_BYTES %du\n#define RENDER_FAR_CODE_BEGIN 0x%xu\n#define RENDER_FAR_CODE_END 0x%xu\n'%(layout_values[0],far_aux['origin'],far_aux['end_exclusive'])
        for name,macro in [('backgroundFarCache','RENDER_BG_FAR_CACHE_BASE'),('backgroundFarMissingRef','RENDER_BG_FAR_MISSING_REF')]:
            if name in symbols:
                size=layout_values[0] if name=='backgroundFarCache' else 2
                assert symbols['__render_bss_begin']<=symbols[name] and symbols[name]+size<=symbols['__render_bss_end']
