#!/usr/bin/env python3
"""Import the eight-pose companion sheet into palette-limited Genesis sprites."""
from pathlib import Path
import json
from PIL import Image
from cps1_gfx import genesis_tiles
from cps1_program import assemble_maincpu
from cps1_palette import palette_words, genesis_color, cps_rgb

ROOT=Path(__file__).resolve().parents[1]

def nearest(c, colors):
    return min(range(len(colors)),key=lambda i:sum((a-b)**2 for a,b in zip(c,colors[i])))

def main():
    out=ROOT/'build';out.mkdir(exist_ok=True)
    im=Image.open(ROOT/'assets/companion/sheet-v2.png').convert('RGBA')
    w,h=im.size
    alpha=im.getchannel('A')
    values=list(alpha.get_flattened_data() if hasattr(alpha,'get_flattened_data') else alpha.getdata())
    mask=bytearray(v>=128 for v in values)
    components=[]
    for at in range(w*h):
        if not mask[at]:continue
        mask[at]=0;queue=[at];points=[]
        while queue:
            i=queue.pop();points.append(i);x=i%w;y=i//w
            for j in (i-1 if x else -1,i+1 if x+1<w else -1,i-w,i+w):
                if 0<=j<w*h and mask[j]:mask[j]=0;queue.append(j)
        if len(points)>100:
            xs=[p%w for p in points];ys=[p//w for p in points]
            components.append((len(points),(min(xs),min(ys),max(xs)+1,max(ys)+1),points))
    components=sorted(components,reverse=True)[:8]
    assert len(components)==8,'Expected eight separated poses'
    components.sort(key=lambda c:(int((c[1][1]+c[1][3])/2>=h/2),c[1][0]))
    # Willow's extracted standing sprite (0x0033) is 36 pixels tall. Import
    # the companion at that scale instead of shrinking a detailed figure to 30.
    scale=36/(components[0][1][3]-components[0][1][1])
    program=assemble_maincpu(ROOT/'willow.zip')
    # Borrow the actual protagonist's skin/brown/red ramps and palette 1's
    # neutral grays. Match imported RGB888 against original CPS colors FIRST;
    # convert the selected palette words to Genesis CRAM only for the output.
    # No pre-fit RGB333 rounding or invented blanket warm tint.
    palette_refs=[(0,0),(1,13),(0,4),(0,3),(0,2),(0,1),(0,6),
                  (1,7),(1,8),(1,9),(1,10),(0,7),(0,8),(0,9),(1,3)]
    words=[palette_words(program,'base',0,group)[pen] for group,pen in palette_refs]
    source_colors=[cps_rgb(word|0xf000) for word in words]
    cram=[genesis_color(c) for c in source_colors]
    colors=[(n>>1&7,n>>5&7,n>>9&7) for n in cram]
    tiles=bytearray();preview=Image.new('RGBA',(192,96));layout=[]
    # Preserve the fully extended fist inside the existing 48-pixel canvas.
    # The renderer compensates this import pivot, so the body's world anchor
    # does not shift when the attack starts or when facing is mirrored.
    pivots=[24,24,24,24,24,24,24,20]
    for index,(_,box,points) in enumerate(components):
        feet=[p%w for p in points if p//w>=box[3]-max(4,int((box[3]-box[1])*.12))]
        anchor=(sum(feet)/len(feet),box[3])
        crop=im.crop(box)
        frame=crop.transform((48,48),Image.Transform.AFFINE,
            (1/scale,0,anchor[0]-box[0]-pivots[index]/scale,0,1/scale,anchor[1]-box[1]-40/scale),Image.Resampling.NEAREST)
        values=frame.get_flattened_data() if hasattr(frame,'get_flattened_data') else frame.getdata()
        pixels=[0 if a<128 else 1+nearest((r,g,b),source_colors) for r,g,b,a in values]
        assert sum(p!=0 for p in pixels)>100
        # Four hardware blocks: 32x32,16x32,32x16,16x16.
        for sy in (0,32):
            for sx in (0,32):
                for tx in range(4 if sx==0 else 2):
                    for ty in range(4 if sy==0 else 2):
                        tiles.extend(genesis_tiles([[pixels[(sy+ty*8+y)*48+sx+tx*8+x] for x in range(8)] for y in range(8)]))
        frame.putdata([(0,0,0,0) if not p else tuple(v*255//7 for v in colors[p-1])+(255,) for p in pixels])
        preview.paste(frame,(index%4*48,index//4*48))
        bounds=frame.getbbox()
        assert bounds and bounds[0]>0 and bounds[2]<48 and bounds[3]<=41, f'Clipped pose {index}: {bounds}'
        layout.append({'box':box,'foot_anchor':anchor,'canvas_pivot_x':pivots[index],
                       'native_bounds':bounds,'opaque_pixels':sum(p!=0 for p in pixels)})
    assert len(tiles)==8*1152
    (out/'companion_sprites.bin').write_bytes(tiles)
    (out/'companion_assets.h').write_text('/* Generated by tools/companion_assets.py. */\nstatic const u16 companion_palette[16]={0,'+','.join(hex(r*2+g*32+b*512) for r,g,b in colors)+'};\nstatic const u8 companion_pose_pivot_x[8]={'+','.join(map(str,pivots))+'};\n')
    (out/'companion_assets.json').write_text(json.dumps({'source_sheet':'assets/companion/sheet-v2.png',
        'scale':scale,'frames':layout,'palette_source_group_pen':palette_refs,
        'palette_cps_words':words,'palette_source_rgb888':source_colors,
        'palette_rgb333':colors},indent=2)+'\n')
    preview.save(out/'companion-sheet-native.png')
    preview.resize((768,384),Image.Resampling.NEAREST).save(out/'companion-sheet-preview.png')
    print(f'Companion: eight poses, {len(tiles)} bytes, 15 source-game colors.')

if __name__=='__main__':main()
