#!/usr/bin/env python3
"""Source-checked Willow command routes; no YM/OKI-to-Genesis playback claims."""
from pathlib import Path
import argparse,hashlib,json,zipfile

def build(sound):
    checks={0x132:'3a00d0473a08f0b8c83200d047e6f0fef0caea0278cb7fc2d203',
      0x14c:'216d0e11700e473e003204f0cd6c01210080110480473e013204f0cd6c0118e0',
      0x16c:'784604b8380290c9c1ebef1acb7fc23002',
      0x1fa:'0608c5131add7701131add7700cd1302013000dd09c110eac9',
      0x2ba:'13dd7200dd7301dd7218dd7319dd360880dd360b80c9',
      0x3d2:'e67fc8',0x3e2:'57cbfa21430ee75fe6f00f3202f0ed5301d0c9',
      0x3f5:'ed5b01d07ab7c87a3202f07b3202f0110000ed5301d0c9'}
    for at,h in checks.items():
        assert sound[at:at+len(bytes.fromhex(h))]==bytes.fromhex(h),hex(at)
    assert len(sound)==65536 and sound[0xe6d]==31 and sound[0xc000]==36 and sound[0xe42]==41
    cues=[]
    for index in range(69):
        bank=int(index>=32);n=index-32 if bank else index;table=0xc004 if bank else 0xe70
        ptr=int.from_bytes(sound[table+n*2:table+n*2+2],'little')
        assert ptr<0xc000
        offset=ptr if ptr<0x8000 else ptr+bank*0x4000;head=sound[offset]
        row={'ordinal':index,'bank':bank,'table_index':n,'pointer':ptr,'rom_offset':offset,'header':head,'priority':head&15,
          'kind':'ym_effect' if head&128 else 'music','prefix_hex':sound[offset:offset+24].hex()}
        if head&128:
            row.update(stream=ptr+1,sound_ram_record=0xd540 if head&64 else 0xd500,ym_channel=6 if head&64 else 7)
        else:
            row['tracks']=[int.from_bytes(sound[offset+1+t*2:offset+3+t*2],'little') for t in range(8)]
        cues.append(row)
    routes=[]
    for cmd in range(256):
        r={'command':cmd}
        if cmd<128:r.update(cues[cmd%69])
        elif cmd<240:
            sample=(cmd&127)%42;vv=sound[0xe43+sample]
            r.update(kind='noop' if cmd==128 else 'direct_oki',sample=sample,voice_volume=vv,stop_byte=(vv&240)>>1,
                     start_sample_byte=128|sample,start_deferred_to_next_timer_b=cmd!=128)
        else:r.update(kind='system',handler=int.from_bytes(sound[0x2ee+(cmd&15)*2:0x2f0+(cmd&15)*2],'little'))
        routes.append(r)
    return cues,routes,checks

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('archive',nargs='?',type=Path,default=Path('willow.zip'))
    ap.add_argument('--output',type=Path,default=Path('build/native-audio-admission/corrected-routes.json'))
    ap.add_argument('--header',type=Path,default=Path('src/willow_native_audio_routes.h'));args=ap.parse_args()
    with zipfile.ZipFile(args.archive) as z:sound=z.read('wl_09.12b')
    cues,routes,checks=build(sound)
    args.output.parent.mkdir(parents=True,exist_ok=True);args.header.parent.mkdir(parents=True,exist_ok=True)
    report={'source':'wl_09.12b','source_sha256':hashlib.sha256(sound).hexdigest(),'scope':'command routing/type/initial pointer metadata, not sequencer execution or sound-chip synthesis',
      'route_rule':'Subtract32 and try fixed table, then subtract37 and try bank1; repeat. A table hit discards the CALL return and dispatches directly. Combined period69.',
      'source_checks':{hex(a):h for a,h in checks.items()},'canonical_cues':cues,'commands':routes,
      'corrections':{'old_catalog_wrong_route_count':96,'old_bank1_music_track_interpretation':'All37 bank1 canonical cues have header bit7 set and enter a single SFX stream, never the eight-track music loader.',
        'stage0_command13':routes[19],'direct_oki':'80 returns without writes; other direct commands first stop the requested voices, then03F5 writes sample and voice/volume at the following timer-B service. Starts are not merely ignored while busy.'}}
    args.output.write_text(json.dumps(report,indent=2)+'\n')
    lines=['#ifndef WILLOW_NATIVE_AUDIO_ROUTES_H','#define WILLOW_NATIVE_AUDIO_ROUTES_H','#include <stdint.h>',
      '/* Generated by tools/native_audio_admission.py from source-checked Z80 bytes.',
      ' * Original sound ROM SHA256 '+report['source_sha256']+'. No playback implementation. */',
      'static const uint16_t willowNativeAudioCue[69][2] = {']
    lines += [f' {{0x{c["pointer"]:04x},0x{c["header"]:04x}}},' for c in cues]
    lines+=['};','static const uint16_t willowNativeAudioOkiVoiceVolume[42] = {',','.join(f'0x{x:02x}' for x in sound[0xe43:0xe43+42]),'};',
      'static const uint16_t willowNativeAudioSystemHandler[16] = {',','.join(f'0x{routes[n]["handler"]:04x}' for n in range(240,256)),'};','#endif']
    args.header.write_text('\n'.join(lines)+'\n')
    print('Corrected256 routes;69 canonical cues:',sum(c['kind']=='music' for c in cues),'music,',sum(c['kind']=='ym_effect' for c in cues),'YM effects; Stage0 cmd13',hex(routes[19]['pointer']),routes[19]['tracks'])
if __name__=='__main__':main()
