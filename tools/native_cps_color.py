#!/usr/bin/env python3
"""Generate/test native CPS-word conversion against the existing art pipeline."""
from pathlib import Path
import argparse
import subprocess
from cps1_palette import cps_rgb, genesis_color

root = Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser()
p.add_argument('--check', action='store_true')
a = p.parse_args()
values = [genesis_color(cps_rgb((brightness << 12) | (channel << 8))) >> 1
          for brightness in range(16) for channel in range(16)]
header = '''#ifndef WILLOW_NATIVE_CPS_COLOR_H
#define WILLOW_NATIVE_CPS_COLOR_H
#include "willow_arcade_player_motion.h"
/* Generated by tools/native_cps_color.py. Apply full CPS RGB444/brightness
 * before RGB333 rounding, exactly matching tools/cps1_palette.py. This is a
 * single-color hardware conversion, not multi-color palette fitting. */
static const uint8_t willowCPSChannelToVDP[256]={
'''
header += '\n'.join(' '+','.join(map(str, values[n:n+16]))+',' for n in range(0,256,16))
header += '''
};
static inline uint16_t willowNativeCPSColor(uint16_t word)
{
 uint16_t brightness=(word>>8)&0xf0;
 return (willowCPSChannelToVDP[brightness|((word>>8)&15)]<<1)|
        (willowCPSChannelToVDP[brightness|((word>>4)&15)]<<5)|
        (willowCPSChannelToVDP[brightness|(word&15)]<<9);
}
#endif
'''
target = root/'src/willow_native_cps_color.h'
if not a.check:
    target.write_text(header)
else:
    assert target.read_text() == header, 'Regenerate native CPS conversion header'
    subprocess.run(['clang','-Wall','-Wextra','-Werror','-O2','-fsanitize=address,undefined',
                    '-fno-sanitize-recover=all','tools/test_native_cps_color.c',
                    '-o','build/test_native_cps_color'],cwd=root,check=True)
    data = subprocess.check_output([str(root/'build/test_native_cps_color')],cwd=root)
    assert len(data) == 131072
    for word in range(65536):
        actual = int.from_bytes(data[word*2:word*2+2], 'big')
        assert actual == genesis_color(cps_rgb(word)), (hex(word),hex(actual))
    print('Native CPS conversion: all 65,536 RGB444/brightness words match the art pipeline; 256-byte ROM table, no persistent RAM')
