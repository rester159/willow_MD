"""Generate address ownership only; never capture live game values."""
from pathlib import Path
import re
root=Path(__file__).resolve().parents[1]
ranges=[]
def add(at,count,pointer):ranges.append((at,count,pointer))
for file,base in [('willow_native_boot_globals.h','sourceBootGlobals.bytes'),('willow_native_pool_auxiliary.h','SOURCE_POOL_AUXILIARY->bytes')]:
    for at,count,offset in re.findall(r'\{(0x[0-9a-f]+),(\d+),(\d+)\}',(root/'src'/file).read_text()):
        add(int(at,16),int(count),f'{base}+{offset}')
for base,rows in [
 ('SOURCE_DEMO_STATE->bytes',[(0x8289,5,0),(0x82c2,129,5),(0x8346,125,134),(0x83c4,7,259),(0x83cc,54,266),(0xf9a2,1,320)]),
 ('SOURCE_DEMO_START_STATE->bytes',[(0xa30,2,0),(0xa3c,1,2),(0xa42,8,3),(0xe68,4,11),(0xf40,64,15),(0xf88,32,79)]),
 ('SOURCE_DEMO_UPDATE_STATE->bytes',[(0xa32,4,0),(0xa3a,2,4),(0xe92,3,6),(0xf08,2,9),(0xfb0,4,11),(0xf892,6,15),(0xf99e,1,21),(0xe96,1,22),(0xfaa,4,23)]),
 ('SOURCE_VISIBILITY_PAYLOAD->bytes',[(0x9356,80,0),(0x946e,352,80),(0x96be,320,432),(0xf466,32,752)])]:
    for at,count,offset in rows:add(at,count,f'{base}+{offset}')
for at,count,base in [
 (0x8402,128,'debugScroll2Record'),(0x8482,128,'debugScroll3Record'),(0x8502,3072,'(u8*)debugStageObjects'),
 (0x9846,128,'debugPlayerRecord.bytes'),(0xefc6,80,'sourceHighScores.records'),(0xf03e,4,'debugHud.highScore'),
 (0xf042,1024,'(u8*)debugPaletteControllers'),(0,512,'taskRecords'),(0x200,16,'sourceTaskState.control.control'),
 (0xa10,32,'sourceTaskState.control.freePointers'),(0x8072,256,'taskCommands'),(0x8172,128,'soundCommands'),
 (0x801a,4,'sourceTaskState.control.ringOffsets'),(0x801e,4,'sourceTaskState.auxiliaryRingOffsets'),
 (0x83c3,1,'(u8*)0x208035UL'),(0x8344,2,'(u8*)0x208036UL')]:add(at,count,base)
ranges.sort()
assert len(ranges)<256
for a,b in zip(ranges,ranges[1:]):assert a[0]+a[1]<=b[0],(a,b)
lines=['/* Generated by tools/native_fixed_data.py. Existing owner addresses only.',
       ' * Differentially checked against the compiled legacy resolver. */',
       '/* Unsigned 32-bit address bias avoids repeating pointer-offset arithmetic.',
       ' * Add the source address only after its ownership/span check succeeds. */',
       'static const struct {u16 first,count;u32 bias;} nativeFixedRanges[]={']
lines += [f'{{0x{a:04x},{n},(u32)({p})-0x{a:04x}UL}},' for a,n,p in ranges]
# Two ROM byte lookups select an owner. Deduplicate identical 32-byte
# ownership blocks, including unmapped pages and long contiguous records.
owners=bytearray([255])*65536
for index,(at,count,_) in enumerate(ranges):owners[at:at+count]=bytes([index])*count
blocks=[];block_ids=[];seen={}
for at in range(0,65536,32):
    block=bytes(owners[at:at+32])
    if block not in seen:seen[block]=len(blocks);blocks.append(block)
    block_ids.append(seen[block])
assert len(blocks)<256
assert b''.join(blocks[i] for i in block_ids)==owners
# Optional startup expansion consumes RAM freed by the actor migration.
# Only owner IDs are encoded; source pointers/game values are never captured.
raw=bytes(block_ids)+b''.join(blocks)
packed=[]
for value in raw:
    if packed and packed[-1]==value and packed[-2]<255:packed[-2]+=1
    else:packed.extend([1,value])
assert b''.join(bytes([value])*count for count,value in zip(packed[::2],packed[1::2]))==raw
# A homogeneous 16-byte half-block may use one prevalidated address bias.
# Mixed halves and holes keep the complete existing ownership lookup.
halves=[]
for block in blocks:
    halves.append([part[0] if len(set(part))==1 and part[0]!=255 else 255
                   for part in (block[:16],block[16:])])
for at in range(65536):
    owner=halves[block_ids[at>>5]][(at>>4)&1]
    assert owner==255 or owner==owners[at]
# A word may use a direct owner only when its two byte-owner IDs agree.
# Even words never cross a 32-byte ownership block.
word_owners=[[block[i] if block[i]==block[i+1] else 255 for i in range(0,32,2)] for block in blocks]
for at in range(0,65536,2):
    owner=word_owners[block_ids[at>>5]][(at>>1)&15]
    expected=owners[at] if owners[at]==owners[at+1] else 255
    assert owner==expected
lines += ['};','#ifdef WILLOW_FIXED_WORD_INDEX_PROBE',
          '#ifndef WILLOW_RAM_FIXED_INDEX_PROBE',
          '#error Word ownership requires the startup RAM index', '#endif',
          'static const u16 nativeFixedWordMasks[] __attribute__((used))={']
word_masks=[sum(1<<i for i,owner in enumerate(row) if owner!=255) for row in word_owners]
for at in range(0,65536,2):
    block=block_ids[at>>5]
    assert bool(word_masks[block] & (1<<((at>>1)&15))) == (word_owners[block][(at>>1)&15]!=255)
lines += [','.join(f'0x{mask:04x}' for mask in word_masks), '};', '#endif', '#ifdef WILLOW_FIXED_BLOCK_BIAS_PROBE',
          '#ifndef WILLOW_RAM_FIXED_INDEX_PROBE',
          '#error Fixed block biases require the startup RAM index', '#endif',
          '#ifdef WILLOW_FIXED_32_BLOCK_PROBE',
          'static u32 nativeFixedBlockBias[2048];',
          '#else','static u32 nativeFixedBlockBias[4096];', '#endif', '#endif',
          '#ifdef WILLOW_RAM_FIXED_INDEX_PROBE',
          f'static struct {{u8 blocks[2048];u8 owners[{len(blocks)}][32];}} nativeFixedIndex;',
          '#define nativeFixedBlocks nativeFixedIndex.blocks',
          '#define nativeFixedOwners nativeFixedIndex.owners',
          f'typedef char NativeFixedIndexSize[(sizeof(nativeFixedIndex)=={len(raw)})?1:-1];',
          'static void sourceFixedIndexInit(void)', '{','static const u8 packed[]={']
for at in range(0,len(packed),32):lines.append(','.join(str(i) for i in packed[at:at+32])+',')
lines += ['};','u8*out=(u8*)&nativeFixedIndex;',
          'for(u16 at=0;at<sizeof(packed);at+=2){u16 count=packed[at];while(count--)*out++=packed[at+1];}',
          '#ifdef WILLOW_FIXED_BLOCK_BIAS_PROBE',
          'static const u8 homogeneous[][2]={']
lines += ['{'+','.join(str(i) for i in row)+'},' for row in halves]
lines += ['};','#ifdef WILLOW_FIXED_32_BLOCK_PROBE',
          'for(u16 block=0;block<2048;block++){',
          'u16 id=nativeFixedBlocks[block],owner=homogeneous[id][0];',
          'nativeFixedBlockBias[block]=(owner==255||owner!=homogeneous[id][1])?0:nativeFixedRanges[owner].bias;',
          '}', '#else', 'for(u16 block=0;block<4096;block++){',
          'u16 owner=homogeneous[nativeFixedBlocks[block>>1]][block&1];',
          'nativeFixedBlockBias[block]=owner==255?0:nativeFixedRanges[owner].bias;',
          '}', '#endif', '#endif', '}', '#else',f'static const u8 nativeFixedOwners[{len(blocks)}][32]={{']
lines += ['{'+','.join(str(i) for i in block)+'},' for block in blocks]
lines += ['};','static const u8 nativeFixedBlocks[2048]={']
for at in range(0,2048,32):lines.append(','.join(str(i) for i in block_ids[at:at+32])+',')
lines += ['};','#endif','static u8*sourceFixedRecordTable(u16 at,u16 bytes)',
 '{','if(!bytes)return 0;',
 'u16 owner=nativeFixedOwners[nativeFixedBlocks[at>>5]][at&31];',
 'if(owner==255)return 0;',
 'u16 offset=at-nativeFixedRanges[owner].first,count=nativeFixedRanges[owner].count;',
 'return offset<count&&bytes<=count-offset?(u8*)(nativeFixedRanges[owner].bias+at):0;}']
lines += ['#ifdef WILLOW_FIXED_OWNER_LEAF_PROBE', '#include "fixed_owner_leaf.h"', '#else',
          '/* The ownership index already proves membership for a single byte.',
          ' * Full-span requests must continue using sourceFixedRecordTable. */',
          'static u8*sourceFixedByte(u16 at)',
          '{', '#ifdef WILLOW_FIXED_BLOCK_BIAS_PROBE',
          '#ifdef WILLOW_FIXED_32_BLOCK_PROBE',
          'u32 bias=nativeFixedBlockBias[at>>5];', '#else',
          'u32 bias=nativeFixedBlockBias[at>>4];', '#endif',
          'if(bias)return (u8*)(bias+at);',
          '#endif', 'u16 owner=nativeFixedOwners[nativeFixedBlocks[at>>5]][at&31];',
          'return owner==255?0:(u8*)(nativeFixedRanges[owner].bias+at);}']
lines += ['#endif', '#if defined(WILLOW_FIXED_WORD_INDEX_PROBE) && !defined(WILLOW_FIXED_OWNER_LEAF_PROBE)',
          'static __attribute__((noinline)) u8*sourceFixedWord(u16 at)', '{', 'if(at&1)return 0;',
          'u16 block=nativeFixedBlocks[at>>5];',
          'u16 mask=nativeFixedWordMasks[block];',
          'if(!mask || (mask!=65535 && !(mask & (1u<<((at>>1)&15)))))return 0;',
          'u16 owner=nativeFixedOwners[block][at&31];',
          'return owner==255?0:(u8*)(nativeFixedRanges[owner].bias+at);}', '#endif']
(root/'native/intro_probe/src/fixed_data.h').write_text('\n'.join(lines)+'\n')
print(f'{len(ranges)} disjoint fixed-owner ranges; {len(blocks)} unique blocks; default {len(raw)} ROM bytes, optional {len(packed)} RLE ROM bytes expanded into {len(raw)} RAM bytes')
