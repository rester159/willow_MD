static uint16_t wordsEqual(const volatile uint32_t*source,const uint32_t*expected,uint16_t longs)
{
 if(!longs)return 1;
 uint16_t remaining=longs-1;uint8_t equal;
 __asm__ volatile("1: cmpm.l (%0)+,(%1)+\n\tdbne %2,1b\n\tseq %3"
                  : "+&a"(source),"+&a"(expected),"+&d"(remaining),"=d"(equal) : : "cc","memory");
 return equal;
}
#ifdef RENDER_RETAINED
static void copyLongs(uint32_t*destination,const volatile uint32_t*source,uint16_t longs)
{
 if(!longs)return;
 uint16_t remaining=longs-1;
 __asm__ volatile("1: move.l (%0)+,(%1)+\n\tdbra %2,1b"
                  : "+&a"(source),"+&a"(destination),"+&d"(remaining) : : "cc","memory");
}
#endif
static void descriptor(uint16_t publish,uint16_t bank,uint16_t records,uint32_t epoch,uint32_t palette)
{
 volatile uint16_t*p=(volatile uint16_t*)(publish?0x20f554:0x20f544);
 p[0]=bank;p[1]=records;*(volatile uint32_t*)(p+2)=epoch;
 *(volatile uint32_t*)(p+4)=palette;*(volatile uint32_t*)(p+6)=1;
}
static void phase(uint16_t n,uint16_t status){WORD(0x20f542)=status;WORD(0x20f540)=(uint16_t)((status<<8)|n);}
static uint16_t initialize(void)
{
 if(state.initialized)return state.initialized==1;
 if(willowPreparedObjectKeyCatalogBind(&state.keys,routeKeys,17,1)||
    willowPreparedObjectStreamBind(&state.stream,&state.keys,state.selections[0],state.selections[1],8)||
    !willowPreparedObjectSeedEmpty(&state.seed,1)||
    !willowNativeSatTargetPrepare(&state.target,0xf400,80)){
  state.initialized=2;phase(6,1);return 0;
 }
 state.initialized=1;phase(6,0);return 1;
}
/* Native writer hooks invalidate BEFORE stores. An interrupted/nested writer
 * cannot admit its partially updated palette. The cached epoch is always
 * rechecked, even if a later interrupt races the READY store. */
static uint16_t certifyPalette(void)
{
 uint32_t epoch=PALETTE_EPOCH;
 if(!epoch||PALETTE_BUSY||!viewReady())return 0;
 if(state.certified&&PALETTE_READY&&state.certifiedEpoch==epoch)return 1;
 state.certified=0;PALETTE_READY=0;
 /* Two actual pointers avoid GCC's cross-bus address-delta induction value;
  * each interrupted register then retains ordinary mapped-pointer identity. */
 if(!wordsEqual((const volatile uint32_t*)PALETTE,renderSourcePalettes,1536))return 0;
 WillowPreparedObjectEpoch bindingEpoch={0,1,epoch,1};
 if(willowPreparedObjectResolvedCatalogBind(&state.resolved,&state.keys,routeShapes,&bindingEpoch,&view)||
    PALETTE_BUSY||PALETTE_EPOCH!=epoch||!viewReady())return 0;
 state.certifiedEpoch=epoch;state.certified=1;PALETTE_READY=1;return 1;
}
