void nativeRenderPrepare(void)
{
 if(!initialize())return;
 uint16_t offset=WORD(0x20f504),bank=offset>>3;
 if(offset!=0&&offset!=8){phase(5,10);return;}
 volatile uint16_t*meta=(volatile uint16_t*)(0x20f508u+offset);
 uint32_t epoch=*(volatile uint32_t*)meta,palette=PALETTE_EPOCH;
 uint16_t records=meta[2];RenderCache*cache=state.caches+bank;
 /* The first gameplay bank is produced during the preceding source state.
  * Admit resources, never infer readiness from the manager/scene label. */
 if(!active()&&(records>8||!viewReady()))return;
#ifdef RENDER_RETAINED
 uint16_t oldReady=cache->ready;
#endif
 cache->ready=0;BARRIER();descriptor(0,bank,records,epoch,palette);phase(1,0);
 if(meta[3]!=1||!epoch||records>8||!certifyPalette()){phase(5,11);return;}
#ifdef RENDER_BACKGROUND_LIVE
 nativeBackgroundPrepare();
#endif
#ifdef RENDER_RETAINED
 if(epoch<state.lastAcceptedEpoch||
    (epoch==state.lastAcceptedEpoch&&(bank!=state.lastAcceptedBank||records!=state.lastAcceptedRecords))){phase(5,12);return;}
#endif
 WillowPreparedObjectEpoch renderEpoch={epoch,1,state.certifiedEpoch,1};
 const uint16_t*input=(const uint16_t*)(bank?BANK1:BANK0);
#ifdef RENDER_RETAINED
 /* Retain only exact complete input, never captured positions or a presumed
  * stable object list. Palette/view/source metadata checks still bracket use. */
 const RenderCache*reuse=cache;
 if(!oldReady||reuse->records!=records||reuse->paletteEpoch!=renderEpoch.palette||
    !wordsEqual((const volatile uint32_t*)input,(const uint32_t*)reuse->sourceWords,records*2)){
  reuse=state.caches+(bank^1);
  if(!reuse->ready||reuse->records!=records||reuse->paletteEpoch!=renderEpoch.palette||
     !wordsEqual((const volatile uint32_t*)input,(const uint32_t*)reuse->sourceWords,records*2))reuse=0;
 }
 if(reuse){
  if(reuse!=cache)copyLongs((uint32_t*)cache->words,(const uint32_t*)reuse->words,reuse->pieces*2);
  cache->pieces=reuse->pieces;cache->geometryId=reuse->geometryId;LONG(0x20f584)++;
  goto geometryReady;
 }
#endif
 WillowPreparedObjectSourceInput source={0,0,epoch,records,256,bank,1};
 const WillowPreparedObjectSelectionPacket*selected;
 uint8_t status=willowPreparedObjectStreamSelect(&state.stream,&source,input,&selected);
 if(!status)status=willowPreparedObjectPublishSelection(&state.resolved,selected,&renderEpoch,state.instances,8,&state.frame,&state.binding);
 if(status){phase(5,20+status);return;}
 WillowObjectSatResult result=willowPreparedObjectBuildSeeded(&state.binding,&renderEpoch,&state.seed,1,&state.budget,cache->words,80,state.deltas);
 if(result.status||result.records!=256){phase(5,30+result.status);return;}
 cache->pieces=result.pieces;
#ifdef RENDER_RETAINED
 cache->geometryId=++state.nextGeometryId;
 if(!cache->geometryId){phase(5,41);return;}
 LONG(0x20f588)++;
geometryReady:
 copyLongs((uint32_t*)cache->sourceWords,(const volatile uint32_t*)input,records*2);
#endif
 if(PALETTE_BUSY||!PALETTE_READY||PALETTE_EPOCH!=renderEpoch.palette||!viewReady()||
    meta[3]!=1||*(volatile uint32_t*)meta!=epoch||meta[2]!=records){phase(5,40);return;}
 cache->sourceEpoch=epoch;cache->paletteEpoch=renderEpoch.palette;cache->records=records;
#ifdef RENDER_RETAINED
 state.lastAcceptedEpoch=epoch;state.lastAcceptedBank=bank;state.lastAcceptedRecords=records;
#endif
 BARRIER();cache->ready=1;phase(2,0);
}
void nativeRenderPublish(void)
{
 if(state.initialized!=1||!active())return;
 uint16_t bank=WORD(0x20f51e),records=WORD(0x20f530);
 uint32_t epoch=LONG(0x20f534),palette=PALETTE_EPOCH;
 descriptor(1,bank,records,epoch,palette);phase(3,0);
 if(bank>1||WORD(0x20f532)!=1){phase(5,50);return;}
 const RenderCache*cache=state.caches+bank;
 if(!cache->ready){phase(5,51);return;}BARRIER();
 if(cache->sourceEpoch!=epoch||cache->records!=records){phase(5,51);return;}
 if(PALETTE_BUSY||!PALETTE_READY||!state.certified||state.certifiedEpoch!=palette||
    cache->paletteEpoch!=palette||!viewReady()){phase(5,52);return;}
 WillowPresentationLease lease={&plan,(const volatile uint32_t*)0x20f568,palette};
 WillowPresentationFrame presentation;
 if(!willowPresentationBegin(&presentation,&lease)||!willowPresentationPrepared(&presentation,WILLOW_PRESENT_OBJECTS)){phase(5,53);return;}
#ifdef RENDER_DIRTY_UPLOAD
 if(!willowNativeSatPublishRetained(&state.target,cache->words,cache->pieces,&presentation,&renderRetained,0)){phase(5,53);return;}
#else
#ifdef RENDER_CONTENT_STREAM
 LONG(0x20f58c)=cache->geometryId;
 if(cache->geometryId&&renderPublishedGeometryId==cache->geometryId&&
    renderPublishedPalette==palette&&renderPublishedCount==cache->pieces){phase(4,0);return;}
#endif
 if(!willowNativeSatPublish(&state.target,cache->words,cache->pieces,&presentation)){phase(5,53);return;}
#ifdef RENDER_CONTENT_STREAM
 renderPublishedGeometryId=cache->geometryId;renderPublishedPalette=palette;renderPublishedCount=cache->pieces;
#endif
#endif
 phase(4,0);
}
/* Cold target resource upload before original source startup. No source game
 * state or captured positions are copied. Initial source RAM clear follows. */
void nativeRenderVDPBoot(void)
{
#ifdef RENDER_BACKGROUND_LOOKUP
 /* Admit the immutable source-key dictionary once; live lookups still
  * require exact complete code/attribute equality on every probe. */
 if(!willowNativeBackgroundLookupValidate((const uint8_t*)WILLOW_BG_LOOKUP_ORIGIN,
    WILLOW_BG_LOOKUP_BYTES,(const uint8_t*)0x120000UL,WILLOW_BG_LOOKUP_CATALOG_BYTES,
    willowBackgroundLookupIndexes))for(;;)__asm__ volatile("stop #0x2700");
#endif
 WORD(0xc00004)=0x8104;WORD(0xc00004)=0x8c81;WORD(0xc00004)=0x8f02;
 LONG(0xc00004)=0x40000000;
 for(uint16_t n=0;n<16384;n++)LONG(0xc00000)=0;
 LONG(0xc00004)=0x7aa00001; /* tile981, 16000 immutable pattern bytes */
 for(uint16_t n=0;n<4000;n++)LONG(0xc00000)=renderPatterns[n];
#ifdef RENDER_BACKGROUND_RESIDENT
 /* Pattern residency only. Original live maps/camera still require their own
  * preparation and publication; no captured map is installed at boot. */
 if(!willowBackgroundResidentLoad((const void*)0x110000,RENDER_BACKGROUND_BYTES))
  for(;;)__asm__ volatile("stop #0x2700");
#endif
 LONG(0xc00004)=0xc0000000;
 for(uint16_t n=0;n<64;n++)WORD(0xc00000)=renderColors[n];
 LONG(0xc00004)=0x40000010;LONG(0xc00000)=0;
 WORD(0xc00004)=0x8230;WORD(0xc00004)=0x8334;WORD(0xc00004)=0x8407;
 WORD(0xc00004)=0x857a;WORD(0xc00004)=0x8700;WORD(0xc00004)=0x8b00;
 WORD(0xc00004)=0x8d3c;WORD(0xc00004)=0x9001;WORD(0xc00004)=0x9100;WORD(0xc00004)=0x9200;
 WORD(0xc00004)=0x8164;
}
