#!/usr/bin/env python3
"""Compile Sorsha's sheet and three source-scene practice arenas to Genesis 4bpp.

Pillow is used only for importing the generated sheet and writing QA previews.
The cartridge uses raw, uncompressed tiles; no image decoder is linked.
"""
from collections import Counter
from pathlib import Path
import argparse
import json
import zipfile

from PIL import Image
from cps1_gfx import assemble_region, decode_tile, genesis_tiles
from cps1_program import assemble_maincpu
from cps1_palette import palette_words, cps_rgb, genesis_color
from cps1_stage_catalog import catalog
from cps1_gameplay_maps import gameplay_map
from native_palette_fit import fit_tile_palettes

ROOT = Path(__file__).resolve().parents[1]
STAGES = (1, 3, 5)
POSES = ('idle', 'walk1', 'walk2', 'walk3', 'walk4', 'crouch', 'jump',
         'fall', 'windup', 'slash', 'followthrough', 'recover',
         'low_slash', 'air_slash', 'hurt', 'victory')


def color_word(c):
    return c[0] * 2 + c[1] * 32 + c[2] * 512


def nearest(c, colors):
    return min(range(len(colors)), key=lambda i: sum((a-b)**2 for a,b in zip(c,colors[i])))


def scenery_chunk(layer_maps, layer, x, y):
    """Select each CPS layer's own map with its authored address dimensions."""
    grid, columns, rows = layer_maps[layer]
    return grid[((rows - 1 - y // 256) % rows) * columns + (x // 256) % columns]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'build')
    out = parser.parse_args().output.resolve()
    out.mkdir(parents=True, exist_ok=True)
    source = ROOT / 'assets/sorsha/sheet.png'
    program = assemble_maincpu(ROOT / 'willow.zip')
    with zipfile.ZipFile(ROOT / 'willow.zip') as z:
        gfx = assemble_region(z)
    # Every chosen CRAM entry occurs in the source game's sprite palettes.
    available = sorted({genesis_color(cps_rgb(w | 0xf000))
                        for stage in STAGES for group in range(32)
                        for w in palette_words(program, 'base', stage, group)[:15]})
    rgb = [(w >> 1 & 7, w >> 5 & 7, w >> 9 & 7) for w in available]
    targets = [(0,0,0),(1,1,1),(1,1,2),(2,2,3),(3,3,4),(4,4,5),
               (6,6,6),(7,7,7),(3,1,0),(5,2,1),(7,3,1),(4,2,1),
               (6,4,3),(7,6,4),(3,3,2)]
    colors = [rgb[nearest(t,rgb)] for t in targets]
    sheet = Image.open(source).convert('RGBA')
    layout = json.loads((source.parent / 'layout.json').read_text())
    assert list(sheet.size) == layout['sheet_size']
    sprites = bytearray()
    preview = Image.new('RGBA', (320,256))
    counts = []
    for frame in range(16):
        # Explicit import rectangles include swords extending beyond grid cells.
        # All poses share a scale and a foot anchor, avoiding size/pivot jitter.
        box=layout['frames'][frame]['box']
        ax,ay=layout['frames'][frame]['anchor']
        scale=layout['scale']
        cropped=sheet.crop(box)
        im=cropped.transform((80,64),Image.Transform.AFFINE,
            (1/scale,0,ax-box[0]-32/scale,0,1/scale,ay-box[1]-56/scale),
            Image.Resampling.NEAREST)
        pixels=[]
        for r,g,b,a in list(im.get_flattened_data() if hasattr(im, 'get_flattened_data') else im.getdata()):
            pixels.append(0 if a < 128 else 1+nearest((r*7/255,g*7/255,b*7/255),colors))
        counts.append(sum(p != 0 for p in pixels))
        assert counts[-1] > 100, f'Empty pose {POSES[frame]}'
        # Two rows of 32+32+16 hardware sprites; the extended canvas keeps
        # horizontal sword strokes intact. Each block is column-major.
        for sy in (0,32):
            for sx in (0,32,64):
                for tx in range(2 if sx==64 else 4):
                    for ty in range(4):
                        tile = [[pixels[(sy+ty*8+j)*80+sx+tx*8+i] for i in range(8)] for j in range(8)]
                        sprites.extend(genesis_tiles(tile))
        image = Image.new('RGBA',(80,64))
        image.putdata([(0,0,0,0) if p==0 else tuple(v*255//7 for v in colors[p-1])+(255,) for p in pixels])
        preview.paste(image,(frame%4*80,frame//4*64))
    assert len(sprites) == 16*80*32
    (out/'sorsha_sprites.bin').write_bytes(sprites)
    preview.resize((960,768),Image.Resampling.NEAREST).save(out/'sorsha-sheet-preview.png')
    headers=['/* Generated by tools/sorsha_assets.py. */',
             'static const u16 sorsha_palette[16] = {0,'+','.join(hex(color_word(c)) for c in colors)+'};']
    enemy_palette=[0]+[genesis_color(cps_rgb(w|0xf000)) for w in palette_words(program,'base',0,1)[:15]]
    headers.append('static const u16 sorsha_enemy_palette[16] = {'+','.join(hex(w) for w in enemy_palette)+'};')
    stages=catalog(program)['stages']
    scenery=bytearray(); offsets=[]; maps=[]; pals=[]; quality=[]
    for stage in STAGES:
        near = gameplay_map(program, stage)
        # 2DBF8 selects foreground Scroll2; 2EB24 selects background Scroll3.
        # Using the latter for both layers selects unrelated foreground chunks.
        layer_maps = {
            'scroll2': (near['chunk_ids'], near['columns'], near['rows']),
            'scroll3': (stages[stage]['chunk_ids'], 16, 16),
        }
        cache={}
        palettes={layer:[[cps_rgb(w|0xf000) for w in palette_words(program,layer,stage,g)] for g in range(32)] for layer in ('scroll2','scroll3')}
        def sample(layer,x,y):
            chunk=scenery_chunk(layer_maps,layer,x,y)
            if not chunk:return None
            size,base,stride,offset=(16,0x80000,0x400,0x4000) if layer=='scroll2' else (32,0xc0000,0x100,0xa00)
            n=256//size;cell=(x//size%n)*n+y//size%n;at=base+chunk*stride+cell*4
            code=int.from_bytes(program[at:at+2],'big');attr=int.from_bytes(program[at+2:at+4],'big')
            code=(code&0x1fff)+offset if layer=='scroll2' else code+offset
            if layer=='scroll3' and not 0xa00<=code<=0xdff:return None
            key=(size,code)
            if key not in cache:cache[key]=decode_tile(gfx,code,size)
            px=x%size;py=y%size
            pen=cache[key][size-1-py if attr&64 else py][size-1-px if attr&32 else px]
            return None if pen==15 else palettes[layer][attr&31][pen]
        cells=[];hist=[Counter(),Counter()]
        for ty in range(28):
            for tx in range(40):
                cell=[]
                for py in range(8):
                    for px in range(8):
                        x=tx*8+px
                        screen_y=ty*8+py
                        # These are practice scenery crops, not source stage
                        # entry coordinates. A tiled source ground strip marks
                        # the prototype's flat collision floor at screen y=192.
                        y=screen_y+{1:32,3:272,5:768}[stage]
                        if screen_y>=192:
                            x=x%32
                            y={1:416,3:480,5:1008}[stage]+screen_y-192
                        c=sample('scroll2',x,y)
                        if c is None:c=sample('scroll3',x,y)
                        cell.append(c or (0,0,0))
                category=int(sum(c[2]-c[0] for c in cell)>0)
                hist[category].update(cell);cells.append(cell)
        # Preserve source RGB888 until fitting each complete tile to hardware.
        ps,assignments,lookup=fit_tile_palettes(cells)
        tiles=[];indices={};tilemap=[];image=Image.new('RGB',(320,224))
        for n,cell in enumerate(cells):
            slot=min(range(2),key=lambda s:sum(lookup[c][s][0] for c in cell))
            pens=[lookup[c][slot][1] for c in cell]
            tile=genesis_tiles([pens[y*8:y*8+8] for y in range(8)])
            if tile not in indices:indices[tile]=len(tiles);tiles.append(tile)
            tilemap.append(indices[tile]|((slot+2)<<13))
            for j,p in enumerate(pens):image.putpixel((n%40*8+j%8,n//40*8+j//8),ps[slot][p-1])
        assert len(tiles)<1120
        offsets.append((len(scenery),len(tiles)));scenery.extend(b''.join(tiles));maps.append(tilemap);pals.append(ps)
        image.save(out/f'sorsha-stage-{stage}-preview.png')
        source_image=Image.new('RGB',(320,224))
        for n,cell in enumerate(cells):
            for j,c in enumerate(cell):source_image.putpixel((n%40*8+j%8,n//40*8+j//8),c)
        source_image.save(out/f'sorsha-stage-{stage}-source.png')
        def rmse(other):
            return (sum(sum((a-b)**2 for a,b in zip(c,d)) for c,d in zip(source_image.getdata(),other.getdata()))/(320*224*3))**0.5
        old_path=out/'visual-before'/f'sorsha-stage-{stage}-preview.png'
        quality.append({'stage':stage,'rgb_rmse':rmse(image),'previous_hardware_rmse':rmse(Image.open(old_path).convert('RGB').point(lambda v:round(v*7/255)*34)) if old_path.exists() else None})
    (out/'sorsha-color-quality.json').write_text(json.dumps(quality,indent=2)+'\n')
    headers.append('static const u32 sorsha_bg_offsets[3] = {'+','.join(str(o) for o,n in offsets)+'};')
    headers.append('static const u16 sorsha_bg_counts[3] = {'+','.join(str(n) for o,n in offsets)+'};')
    headers.append('static const u16 sorsha_bg_palettes[3][2][16] = {')
    for ps in pals:headers.append('{'+','.join('{0,'+','.join(hex(color_word(tuple(v//34 for v in c))) for c in p)+'}' for p in ps)+'},')
    headers.append('};\nstatic const u16 sorsha_bg_maps[3][1120] = {')
    for m in maps:headers.append('{'+','.join(hex(v) for v in m)+'},')
    headers.append('};')
    (out/'sorsha_assets.h').write_text('\n'.join(headers)+'\n')
    (out/'sorsha_backgrounds.bin').write_bytes(scenery)
    (out/'sorsha_assets.json').write_text(json.dumps({'poses':POSES,'opaque_pixels':counts,'source_stages':STAGES,'sprite_bytes':len(sprites),'background_bytes':len(scenery),'palette_words':[color_word(c) for c in colors]},indent=2)+'\n')
    print(f'Sorsha: {len(sprites)} sprite bytes; {len(scenery)} scenery bytes')


if __name__ == '__main__':
    main()
